class TargetReferenceUpdateGate:
    """Select safe frames for rolling target-only visual references."""

    def __init__(
        self,
        *,
        interval_frames: int,
        min_confidence: float,
    ) -> None:
        if interval_frames <= 0:
            raise ValueError("reference update interval must be positive")
        self.interval_frames = int(interval_frames)
        self.min_confidence = float(min_confidence)

    def consider(
        self,
        frame_index: int,
        *,
        confidence: float,
    ) -> tuple[bool, str]:
        if confidence < self.min_confidence:
            return False, "low_confidence"
        if frame_index % self.interval_frames:
            return False, "not_due"
        return True, "interval"


class AsyncTargetReferenceUpdater:
    """Run YOLOE reference extraction off the servo thread, latest request wins."""

    _STOP = object()

    def __init__(
        self,
        encoder_factory: Callable[[], Any],
        *,
        min_confidence: float,
        min_iou: float,
    ) -> None:
        self._encoder_factory = encoder_factory
        self._min_confidence = float(min_confidence)
        self._min_iou = float(min_iou)
        self._requests: queue.Queue[Any] = queue.Queue(maxsize=1)
        self._results: queue.Queue[TargetReferenceUpdateResult] = queue.Queue(maxsize=1)
        self._closed = threading.Event()
        self._thread = threading.Thread(
            target=self._run,
            name="yoloe-target-reference-updater",
            daemon=True,
        )
        self._thread.start()

    @staticmethod
    def _put_latest(destination: queue.Queue[Any], item: Any) -> None:
        while True:
            try:
                destination.put_nowait(item)
                return
            except queue.Full:
                try:
                    destination.get_nowait()
                except queue.Empty:
                    pass

    def submit(self, request: TargetReferenceRequest) -> None:
        if self._closed.is_set():
            return
        safe_request = replace(
            request,
            rgb=np.ascontiguousarray(request.rgb.copy()),
        )
        self._put_latest(self._requests, safe_request)

    def poll_latest(self) -> TargetReferenceUpdateResult | None:
        latest = None
        while True:
            try:
                latest = self._results.get_nowait()
            except queue.Empty:
                return latest

    def close(self) -> None:
        if self._closed.is_set():
            return
        self._closed.set()
        self._put_latest(self._requests, self._STOP)
        self._thread.join(timeout=10.0)

    @staticmethod
    def _result(
        request: TargetReferenceRequest,
        *,
        accepted: bool,
        reason: str,
        embedding: Any | None = None,
        confidence: float | None = None,
        iou: float | None = None,
    ) -> TargetReferenceUpdateResult:
        return TargetReferenceUpdateResult(
            generation=request.generation,
            frame_index=request.frame_index,
            accepted=accepted,
            embedding=embedding,
            confidence=confidence,
            iou=iou,
            reason=reason,
        )

    def _validate(
        self,
        request: TargetReferenceRequest,
        encoded: EncodedTargetReference,
    ) -> TargetReferenceUpdateResult:
        confidence = float(encoded.confidence)
        if encoded.bbox_xyxy is None:
            return self._result(
                request,
                accepted=False,
                reason="no_detection",
                confidence=confidence,
            )
        overlap = bbox_iou(encoded.bbox_xyxy, request.target_bbox_xyxy)
        if confidence < self._min_confidence:
            return self._result(
                request,
                accepted=False,
                reason="confidence_below_threshold",
                confidence=confidence,
                iou=overlap,
            )
        if overlap < self._min_iou:
            return self._result(
                request,
                accepted=False,
                reason="iou_below_threshold",
                confidence=confidence,
                iou=overlap,
            )
        return self._result(
            request,
            accepted=True,
            reason="accepted",
            embedding=encoded.embedding,
            confidence=confidence,
            iou=overlap,
        )

    def _run(self) -> None:
        encoder = None
        try:
            encoder = self._encoder_factory()
        except Exception:
            # Retry against the first request so initialization failure is reported.
            pass
        while True:
            item = self._requests.get()
            if item is self._STOP:
                return
            if not isinstance(item, TargetReferenceRequest):
                continue
            request = item
            try:
                if encoder is None:
                    encoder = self._encoder_factory()
                encoded = encoder.extract(request)
                result = self._validate(request, encoded)
            except Exception as exc:
                result = self._result(
                    request,
                    accepted=False,
                    reason=f"error:{type(exc).__name__}:{exc}",
                )
            if self._closed.is_set():
                return
            self._put_latest(self._results, result)


class YoloePersistentTracker:
    """YOLOE-26M segmentation plus persistent BoT-SORT IDs."""

    def __init__(
        self,
        model_path: str | Path = DEFAULT_YOLOE_MODEL,
        *,
        confidence: float = 0.25,
        imgsz: int = 640,
        device: str = "0",
    ):
        path = Path(model_path).resolve()
        if not path.is_file():
            raise FileNotFoundError(f"YOLOE model not found: {path}")
        os.environ.setdefault(
            "YOLO_CONFIG_DIR", str(path.parents[1] / "config")
        )
        os.environ.setdefault("YOLO_AUTOINSTALL", "false")
        try:
            import lap  # noqa: F401
            import torch
            from ultralytics import YOLOE
        except ImportError as exc:
            raise RuntimeError(
                "raw YOLOE servo requires ultralytics, torch, and lap in "
                ".venv_inference"
            ) from exc
        if not torch.cuda.is_available():
            raise RuntimeError("raw YOLOE servo requires a CUDA GPU")
        self.model = YOLOE(str(path))
        self.confidence = float(confidence)
        self.imgsz = int(imgsz)
        self.device = device
        self.class_names: tuple[str, str] | None = None
        self._initial_surface_embedding: Any | None = None

    def start_all_text(
        self,
        *,
        target_prompt: str,
        surface_prompt: str,
    ) -> dict[str, Any]:
        """Install text embeddings for both classes and clear track state."""
        target = str(target_prompt).strip()
        surface = str(surface_prompt).strip()
        if not target or not surface:
            raise ValueError("YOLOE text prompts must be non-empty")
        embeddings = self.model.get_text_pe([target, surface])
        if embeddings.ndim != 3 or embeddings.shape[1] != 2:
            raise RuntimeError(
                "YOLOE expected two text class embeddings, got "
                f"{tuple(embeddings.shape)}"
            )
        self.class_names = (target, surface)
        self._initial_surface_embedding = embeddings[:, 1:2].detach().clone()
        self.model.set_classes(list(self.class_names), embeddings=embeddings)
        self.model.predictor = None
        return {
            "class_names": list(self.class_names),
            "prompt_mode": "target_text_surface_text",
        }

    def start_text(
        self,
        reference_rgb: np.ndarray,
        *,
        target_prompt: str,
        target_bbox: tuple[float, float, float, float],
        surface_prompt: str,
        surface_bboxes: Sequence[tuple[float, float, float, float]],
    ) -> dict[str, Any]:
        """Install a text target plus visual surface and clear track state."""
        target = str(target_prompt).strip()
        surface = str(surface_prompt).strip()
        if not target or not surface:
            raise ValueError("YOLOE text prompts must be non-empty")
        visual = self.start(
            reference_rgb,
            target_prompt=target,
            target_bbox=target_bbox,
            surface_prompt=surface,
            surface_bboxes=surface_bboxes,
        )
        target_embedding = self.model.get_text_pe([target])
        self.install_target_embedding(target_embedding)
        self.model.predictor = None
        return {
            "class_names": list(self.class_names),
            "prompt_mode": "target_text_surface_visual",
            "reference_boxes_xyxy": visual["reference_boxes_xyxy"],
            "reference_class_ids": visual["reference_class_ids"],
        }

    def start(
        self,
        reference_rgb: np.ndarray,
        *,
        target_prompt: str,
        target_bbox: tuple[float, float, float, float],
        surface_prompt: str,
        surface_bboxes: Sequence[tuple[float, float, float, float]],
    ) -> dict[str, Any]:
        """Install two reference-box visual classes and clear old track state."""
        from ultralytics.models.yolo.yoloe import YOLOEVPSegPredictor

        if reference_rgb.ndim != 3 or reference_rgb.shape[2] != 3:
            raise ValueError("YOLOE reference image must be an HxWx3 RGB array")
        if not surface_bboxes:
            raise ValueError("YOLOE requires at least one table reference box")
        height, width = reference_rgb.shape[:2]
        self.class_names = (target_prompt, surface_prompt)
        normalized_boxes = (target_bbox, *surface_bboxes)
        prompt_boxes = np.asarray(
            [
                normalized_bbox_to_pixels(bbox, width, height)
                for bbox in normalized_boxes
            ],
            dtype=np.float32,
        )
        prompt_classes = np.asarray(
            [0, *([1] * len(surface_bboxes))], dtype=np.int32
        )
        bgr = cv2.cvtColor(reference_rgb, cv2.COLOR_RGB2BGR)

        # YOLOE first extracts one visual embedding per class from the boxed
        # reference frame. Its regular segmentation predictor then uses those
        # embeddings for this frame and all subsequent tracking frames.
        results = self.model.predict(
            source=bgr,
            refer_image=bgr,
            visual_prompts={"bboxes": prompt_boxes, "cls": prompt_classes},
            predictor=YOLOEVPSegPredictor,
            device=self.device,
            imgsz=self.imgsz,
            conf=self.confidence,
            half=True,
            quantize=16,
            verbose=False,
            save=False,
        )
        if len(results) != 1:
            raise RuntimeError(
                f"YOLOE visual-prompt initialization returned {len(results)} results"
            )
        embeddings = getattr(self.model.model, "pe", None)
        if embeddings is None:
            raise RuntimeError("YOLOE did not produce visual prompt embeddings")
        if embeddings.ndim != 3 or embeddings.shape[1] != 2:
            raise RuntimeError(
                f"YOLOE expected two class embeddings, got {tuple(embeddings.shape)}"
            )
        self._initial_surface_embedding = embeddings[:, 1:2].detach().clone()
        # Preserve the visual embeddings while replacing object0/object1 with
        # readable labels. Recreating the predictor also clears BoT-SORT state
        # between operator requests.
        self.model.set_classes(list(self.class_names), embeddings=embeddings)
        self.model.predictor = None
        return {
            "class_names": list(self.class_names),
            "reference_boxes_xyxy": prompt_boxes.tolist(),
            "reference_class_ids": prompt_classes.tolist(),
        }

    def install_target_embedding(self, embedding: Any) -> None:
        """Atomically replace target PE while retaining table PE and tracker state."""
        import torch

        if self.class_names is None:
            raise RuntimeError("YOLOE classes have not been initialized")
        surface = self._initial_surface_embedding
        if surface is None:
            raise RuntimeError("initial table embedding is unavailable")
        target = embedding.detach().to(
            device=surface.device,
            dtype=surface.dtype,
        )
        if target.ndim != 3 or target.shape[1] != 1:
            raise ValueError(
                f"target embedding has invalid shape {tuple(target.shape)}"
            )
        if tuple(target.shape) != tuple(surface.shape):
            raise ValueError(
                "target and table embedding shapes differ: "
                f"{tuple(target.shape)} != {tuple(surface.shape)}"
            )
        hybrid = torch.cat((target, surface), dim=1)
        self.model.set_classes(list(self.class_names), embeddings=hybrid)

    def install_surface_embedding(self, embedding: Any) -> None:
        """Atomically replace surface PE while retaining target PE and tracker state."""
        import torch

        if self.class_names is None:
            raise RuntimeError("YOLOE classes have not been initialized")
        current = getattr(self.model.model, "pe", None)
        if current is None or current.ndim != 3 or current.shape[1] != 2:
            raise RuntimeError("current target/surface embeddings are unavailable")
        target = current[:, :1].detach().clone()
        surface = embedding.detach().to(
            device=target.device,
            dtype=target.dtype,
        )
        if surface.ndim != 3 or surface.shape[1] != 1:
            raise ValueError(
                f"surface embedding has invalid shape {tuple(surface.shape)}"
            )
        if tuple(surface.shape) != tuple(target.shape):
            raise ValueError(
                "target and surface embedding shapes differ: "
                f"{tuple(target.shape)} != {tuple(surface.shape)}"
            )
        self._initial_surface_embedding = surface.detach().clone()
        hybrid = torch.cat((target, surface), dim=1)
        self.model.set_classes(list(self.class_names), embeddings=hybrid)

    def install_reference_embeddings(
        self,
        *,
        target_embedding: Any,
        surface_embedding: Any,
    ) -> None:
        """Atomically replace both visual PEs without resetting tracker state."""
        import torch

        if self.class_names is None:
            raise RuntimeError("YOLOE classes have not been initialized")
        current = getattr(self.model.model, "pe", None)
        if current is None or current.ndim != 3 or current.shape[1] != 2:
            raise RuntimeError("current target/surface embeddings are unavailable")
        template = current[:, :1]
        target = target_embedding.detach().to(
            device=template.device,
            dtype=template.dtype,
        )
        surface = surface_embedding.detach().to(
            device=template.device,
            dtype=template.dtype,
        )
        if target.ndim != 3 or target.shape[1] != 1:
            raise ValueError(
                f"target embedding has invalid shape {tuple(target.shape)}"
            )
        if surface.ndim != 3 or surface.shape[1] != 1:
            raise ValueError(
                f"surface embedding has invalid shape {tuple(surface.shape)}"
            )
        if tuple(target.shape) != tuple(surface.shape):
            raise ValueError(
                "target and surface embedding shapes differ: "
                f"{tuple(target.shape)} != {tuple(surface.shape)}"
            )
        self._initial_surface_embedding = surface.detach().clone()
        hybrid = torch.cat((target, surface), dim=1)
        self.model.set_classes(list(self.class_names), embeddings=hybrid)

    def track(self, rgb: np.ndarray) -> list[TrackedInstance]:
        if self.class_names is None:
            raise RuntimeError("YOLOE classes have not been initialized")
        from ultralytics.utils import ops

        bgr = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
        result = self.model.track(
            bgr,
            persist=True,
            tracker="botsort.yaml",
            device=self.device,
            imgsz=self.imgsz,
            conf=self.confidence,
            half=True,
            quantize=16,
            verbose=False,
            save=False,
        )[0]
        if result.boxes is None or result.masks is None or result.boxes.id is None:
            return []
        boxes = result.boxes.xyxy.detach().cpu().numpy()
        classes = result.boxes.cls.detach().cpu().numpy().astype(int)
        confidences = result.boxes.conf.detach().cpu().numpy()
        ids = result.boxes.id.detach().cpu().numpy().astype(int)
        mask_data = result.masks.data
        scaled = ops.scale_masks(
            mask_data[:, None], rgb.shape[:2], padding=True, mode="nearest"
        )[:, 0]
        masks = scaled.detach().cpu().numpy() > 0.5
        instances: list[TrackedInstance] = []
        for index, track_id in enumerate(ids):
            class_index = int(classes[index])
            if class_index < 0 or class_index >= len(self.class_names):
                continue
            instances.append(
                TrackedInstance(
                    track_id=int(track_id),
                    class_index=class_index,
                    class_name=self.class_names[class_index],
                    confidence=float(confidences[index]),
                    bbox_xyxy=tuple(float(item) for item in boxes[index]),
                    mask=masks[index],
                )
            )
        return instances


class YoloeTargetReferenceEncoder:
    """Independent YOLOE model used only to refresh a target visual prompt."""

    def __init__(
        self,
        model_path: str | Path = DEFAULT_YOLOE_MODEL,
        *,
        confidence: float = 0.25,
        imgsz: int = 640,
        device: str = "0",
    ) -> None:
        path = Path(model_path).resolve()
        if not path.is_file():
            raise FileNotFoundError(f"YOLOE model not found: {path}")
        os.environ.setdefault("YOLO_CONFIG_DIR", str(path.parents[1] / "config"))
        os.environ.setdefault("YOLO_AUTOINSTALL", "false")
        try:
            import torch
            from ultralytics import YOLOE
        except ImportError as exc:
            raise RuntimeError(
                "raw YOLOE servo requires ultralytics and torch in "
                ".venv_inference"
            ) from exc
        if not torch.cuda.is_available():
            raise RuntimeError("raw YOLOE servo requires a CUDA GPU")
        self.model = YOLOE(str(path))
        self.confidence = float(confidence)
        self.imgsz = int(imgsz)
        self.device = device

    def extract(
        self,
        request: TargetReferenceRequest,
    ) -> EncodedTargetReference:
        from ultralytics.models.yolo.yoloe import YOLOEVPSegPredictor

        rgb = request.rgb
        if rgb.ndim != 3 or rgb.shape[2] != 3:
            raise ValueError("YOLOE reference image must be an HxWx3 RGB array")
        bgr = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
        prompt_boxes = np.asarray(
            [request.target_bbox_xyxy],
            dtype=np.float32,
        )
        prompt_classes = np.asarray([0], dtype=np.int32)
        self.model.predictor = None
        try:
            results = self.model.predict(
                source=bgr,
                refer_image=bgr,
                visual_prompts={
                    "bboxes": prompt_boxes,
                    "cls": prompt_classes,
                },
                predictor=YOLOEVPSegPredictor,
                device=self.device,
                imgsz=self.imgsz,
                conf=self.confidence,
                half=True,
                quantize=16,
                verbose=False,
                save=False,
            )
        finally:
            self.model.predictor = None
        if len(results) != 1:
            raise RuntimeError(
                f"YOLOE target reference returned {len(results)} results"
            )
        embeddings = getattr(self.model.model, "pe", None)
        if embeddings is None:
            raise RuntimeError("YOLOE did not produce a target visual embedding")
        if embeddings.ndim != 3 or embeddings.shape[1] != 1:
            raise RuntimeError(
                f"YOLOE expected one target embedding, got {tuple(embeddings.shape)}"
            )
        embedding = embeddings[:, :1].detach().clone()
        result = results[0]
        if result.boxes is None or len(result.boxes) == 0:
            return EncodedTargetReference(
                embedding=embedding,
                confidence=0.0,
                bbox_xyxy=None,
            )
        boxes = [
            tuple(float(value) for value in row)
            for row in result.boxes.xyxy.detach().cpu().numpy()
        ]
        classes = result.boxes.cls.detach().cpu().numpy().astype(int)
        confidences = result.boxes.conf.detach().cpu().numpy()
        candidates = [index for index, value in enumerate(classes) if value == 0]
        if not candidates:
            return EncodedTargetReference(
                embedding=embedding,
                confidence=0.0,
                bbox_xyxy=None,
            )
        best_index = max(
            candidates,
            key=lambda index: (
                bbox_iou(boxes[index], request.target_bbox_xyxy),
                float(confidences[index]),
            ),
        )
        return EncodedTargetReference(
            embedding=embedding,
            confidence=float(confidences[best_index]),
            bbox_xyxy=boxes[best_index],
        )


def select_initial_instance(
    instances: list[TrackedInstance],
    *,
    class_index: int,
    grounded_bboxes: Sequence[tuple[float, float, float, float]],
    width: int,
    height: int,
) -> TrackedInstance:
    if not grounded_bboxes:
        raise ValueError("at least one grounded bbox is required")
    expected = tuple(
        normalized_bbox_to_pixels(bbox, width, height) for bbox in grounded_bboxes
    )
    candidates = [item for item in instances if item.class_index == class_index]
    if not candidates:
        raise RuntimeError(f"YOLOE found no instance for class index {class_index}")

    def best_iou(item: TrackedInstance) -> float:
        return max(bbox_iou(item.bbox_xyxy, bbox) for bbox in expected)

    ranked = sorted(
        candidates,
        key=lambda item: (best_iou(item), item.confidence),
        reverse=True,
    )
    chosen = ranked[0]
    if best_iou(chosen) < 0.05:
        raise RuntimeError(
            f"YOLOE class {class_index} does not overlap any grounded bbox"
        )
    return chosen


def _depth_points(
    snapshot: AlignedRGBDSnapshot,
    mask: np.ndarray,
    calibration: RawServoCalibration,
    *,
    erode_px: int,
    min_pixels: int,
    min_valid_ratio: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, float]:
    calibration.validate_snapshot(snapshot)
    assert snapshot.depth_raw is not None
    assert snapshot.depth_scale_m is not None
    binary = np.asarray(mask, dtype=np.uint8)
    if binary.shape != snapshot.depth_raw.shape:
        raise ValueError("segmentation mask is not aligned to RGB-D")
    if erode_px > 0:
        kernel_size = erode_px * 2 + 1
        kernel = np.ones((kernel_size, kernel_size), dtype=np.uint8)
        binary = cv2.erode(binary, kernel, iterations=1)
    total = int(np.count_nonzero(binary))
    if total == 0:
        raise ValueError("segmentation mask is empty after erosion")
    depth_m = snapshot.depth_raw.astype(np.float64) * snapshot.depth_scale_m
    valid_mask = (binary > 0) & np.isfinite(depth_m) & (depth_m >= 0.10) & (depth_m <= 10.0)
    valid_count = int(np.count_nonzero(valid_mask))
    valid_ratio = valid_count / total
    if valid_count < min_pixels or valid_ratio < min_valid_ratio:
        raise ValueError(
            f"insufficient valid mask depth: {valid_count} pixels, ratio={valid_ratio:.3f}"
        )
    v, u = np.nonzero(valid_mask)
    z = depth_m[v, u]
    p10, p90 = np.percentile(z, [10.0, 90.0])
    keep = (z >= p10) & (z <= p90)
    return u[keep], v[keep], z[keep], valid_ratio


def _deproject(
    u: np.ndarray, v: np.ndarray, z: np.ndarray, calibration: RawServoCalibration
) -> np.ndarray:
    return np.column_stack(
        (
            (u - calibration.cx) * z / calibration.fx,
            (v - calibration.cy) * z / calibration.fy,
            z,
        )
    )


def estimate_target_geometry(
    snapshot: AlignedRGBDSnapshot,
    mask: np.ndarray,
    calibration: RawServoCalibration,
    *,
    bbox_xyxy: tuple[float, float, float, float] | None = None,
    erode_px: int = 5,
    min_pixels: int = 200,
    min_valid_ratio: float = 0.30,
) -> TargetGeometry:
    u, v, z, valid_ratio = _depth_points(
        snapshot,
        mask,
        calibration,
        erode_px=erode_px,
        min_pixels=min_pixels,
        min_valid_ratio=min_valid_ratio,
    )
    body = calibration.camera_to_body(_deproject(u, v, z, calibration))
    median = np.median(body, axis=0)
    right_m = float(-median[1])
    lateral_anchor_px = None
    if bbox_xyxy is not None:
        # The lateral loop follows the requested box center; mask depth supplies
        # a robust range rather than a fragile center pixel.
        u_center = 0.5 * (bbox_xyxy[0] + bbox_xyxy[2])
        v_center = float(np.median(v))
        z_center = float(np.median(z))
        center_camera = _deproject(
            np.array([u_center]),
            np.array([v_center]),
            np.array([z_center]),
            calibration,
        )
        right_m = float(-calibration.camera_to_body(center_camera)[0, 1])
        lateral_anchor_px = (float(u_center), float(v_center))
    return TargetGeometry(
        forward_m=float(median[0]),
        right_m=right_m,
        body_xyz_m=tuple(float(item) for item in median),
        valid_depth_pixels=int(z.size),
        valid_ratio=float(valid_ratio),
        median_depth_m=float(np.median(z)),
        lateral_anchor_px=lateral_anchor_px,
    )


_TABLE_EDGE_GAUSSIAN_KERNEL = 5
_TABLE_EDGE_CANNY_LOW = 50
_TABLE_EDGE_CANNY_HIGH = 150
_TABLE_EDGE_HOUGH_THRESHOLD = 25
_TABLE_EDGE_MIN_LENGTH_PX = 45.0
_TABLE_EDGE_HOUGH_MAX_LINE_GAP_PX = 12
_TABLE_EDGE_DEPTH_SAMPLES = 20


@dataclass(frozen=True)
class _TLSSegment:
    points: np.ndarray
    center: np.ndarray
    direction: np.ndarray
    residual_q90: float
    residual_median: float
    length: float
    endpoint_a: np.ndarray
    endpoint_b: np.ndarray


@dataclass(frozen=True)
class _PixelLineSegment:
    endpoint_a: np.ndarray
    endpoint_b: np.ndarray
    length: float


def _fit_tls_segment(points: np.ndarray) -> _TLSSegment:
    values = np.asarray(points, dtype=np.float64)
    if values.ndim != 2 or values.shape[1] != 2 or len(values) < 2:
        raise ValueError("TLS line fitting requires at least two 2D points")
    center = np.mean(values, axis=0)
    centered = values - center
    if np.allclose(centered, 0.0):
        direction = np.array([1.0, 0.0], dtype=np.float64)
    else:
        _, _, vh = np.linalg.svd(centered, full_matrices=False)
        direction = vh[0]
    direction /= max(float(np.linalg.norm(direction)), 1e-12)
    normal = np.array([-direction[1], direction[0]])
    residuals = np.abs(centered @ normal)
    projection = centered @ direction
    minimum = float(np.min(projection))
    maximum = float(np.max(projection))
    return _TLSSegment(
        points=values,
        center=center,
        direction=direction,
        residual_q90=float(np.quantile(residuals, 0.90)),
        residual_median=float(np.median(residuals)),
        length=maximum - minimum,
        endpoint_a=center + minimum * direction,
        endpoint_b=center + maximum * direction,
    )


def _rgb_mask_edge_intersection(
    rgb: np.ndarray,
    mask: np.ndarray,
    *,
    exclusion_mask: np.ndarray | None = None,
) -> np.ndarray:
    image = np.asarray(rgb)
    binary = np.asarray(mask) > 0
    if image.ndim != 3 or image.shape[2] != 3:
        raise ValueError("table-edge RGB image must have three channels")
    if binary.ndim != 2 or binary.shape != image.shape[:2]:
        raise ValueError("table mask is not aligned to RGB")
    effective_mask = binary.copy()
    if exclusion_mask is not None:
        excluded = np.asarray(exclusion_mask) > 0
        if excluded.shape != binary.shape:
            raise ValueError("table-edge exclusion mask is not aligned")
        effective_mask[excluded] = False

    gray = cv2.cvtColor(image, cv2.COLOR_RGB2GRAY)
    blurred = cv2.GaussianBlur(
        gray,
        (_TABLE_EDGE_GAUSSIAN_KERNEL, _TABLE_EDGE_GAUSSIAN_KERNEL),
        0,
    )
    edges = cv2.Canny(
        blurred,
        _TABLE_EDGE_CANNY_LOW,
        _TABLE_EDGE_CANNY_HIGH,
        apertureSize=3,
        L2gradient=True,
    )
    intersection = np.zeros_like(edges)
    intersection[effective_mask] = edges[effective_mask]
    return intersection


def _rgb_mask_line_segments(
    rgb: np.ndarray,
    mask: np.ndarray,
    *,
    exclusion_mask: np.ndarray | None = None,
) -> list[_PixelLineSegment]:
    intersection = _rgb_mask_edge_intersection(
        rgb,
        mask,
        exclusion_mask=exclusion_mask,
    )
    detected = cv2.HoughLinesP(
        intersection,
        rho=1.0,
        theta=np.pi / 180.0,
        threshold=_TABLE_EDGE_HOUGH_THRESHOLD,
        minLineLength=_TABLE_EDGE_MIN_LENGTH_PX,
        maxLineGap=_TABLE_EDGE_HOUGH_MAX_LINE_GAP_PX,
    )
    segments: list[_PixelLineSegment] = []
    if detected is not None:
        for x1, y1, x2, y2 in detected[:, 0, :]:
            endpoint_a = np.array([x1, y1], dtype=np.float64)
            endpoint_b = np.array([x2, y2], dtype=np.float64)
            length = float(np.linalg.norm(endpoint_b - endpoint_a))
            if length > _TABLE_EDGE_MIN_LENGTH_PX:
                segments.append(
                    _PixelLineSegment(
                        endpoint_a=endpoint_a,
                        endpoint_b=endpoint_b,
                        length=length,
                    )
                )
    return sorted(segments, key=lambda segment: segment.length, reverse=True)


def _select_nearest_pixel_segment(
    segments: Sequence[_PixelLineSegment],
    *,
    depth_raw: np.ndarray,
    depth_scale_m: float,
) -> tuple[_PixelLineSegment, np.ndarray, np.ndarray]:
    if depth_raw.ndim != 2 or not math.isfinite(depth_scale_m):
        raise ValueError("table-edge depth source is invalid")
    best: tuple[
        float, _PixelLineSegment, np.ndarray, np.ndarray
    ] | None = None
    for segment in segments:
        sampled_pixels = np.rint(
            np.linspace(
                segment.endpoint_a,
                segment.endpoint_b,
                _TABLE_EDGE_DEPTH_SAMPLES,
            )
        ).astype(int)
        sampled_u = sampled_pixels[:, 0]
        sampled_v = sampled_pixels[:, 1]
        if not (
            np.all((0 <= sampled_v) & (sampled_v < depth_raw.shape[0]))
            and np.all((0 <= sampled_u) & (sampled_u < depth_raw.shape[1]))
        ):
            continue
        sampled_depth_m = (
            depth_raw[sampled_v, sampled_u].astype(np.float64)
            * depth_scale_m
        )
        if not np.all(
            np.isfinite(sampled_depth_m)
            & (sampled_depth_m >= 0.15)
            & (sampled_depth_m <= 4.0)
        ):
            continue
        mean_depth_m = float(np.mean(sampled_depth_m))
        if (
            best is None
            or mean_depth_m < best[0]
            or (
                mean_depth_m == best[0]
                and segment.length > best[1].length
            )
        ):
            best = (
                mean_depth_m,
                segment,
                sampled_pixels,
                sampled_depth_m,
            )
    if best is None:
        raise ValueError(
            "no RGB-mask table-edge line has 20 valid sampled depths"
        )
    return best[1], best[2], best[3]


def _largest_filled_component(mask: np.ndarray) -> np.ndarray:
    binary = (np.asarray(mask) > 0).astype(np.uint8)
    if binary.ndim != 2:
        raise ValueError("table mask must be two-dimensional")
    component_count, labels, stats, _ = cv2.connectedComponentsWithStats(
        binary,
        connectivity=8,
    )
    if component_count <= 1:
        return binary

    largest_label = 1 + int(
        np.argmax(stats[1:, cv2.CC_STAT_AREA])
    )
    largest = (labels == largest_label).astype(np.uint8)

    padded = np.pad(largest, 1, mode="constant", constant_values=0)
    flooded = padded.copy()
    cv2.floodFill(flooded, None, (0, 0), 2)
    holes = flooded[1:-1, 1:-1] == 0
    largest[holes] = 1
    return largest


def _binary_mask_row_spans(
    mask: np.ndarray,
) -> tuple[tuple[int, int, int], ...]:
    """Encode a binary mask as (row, start, exclusive-end) runs."""
    binary = np.asarray(mask) > 0
    if binary.ndim != 2:
        raise ValueError("desk mask must be two-dimensional")
    spans: list[tuple[int, int, int]] = []
    for row_index, row in enumerate(binary):
        padded = np.pad(row, (1, 1), mode="constant", constant_values=False)
        transitions = np.flatnonzero(padded[1:] != padded[:-1])
        spans.extend(
            (int(row_index), int(start), int(end))
            for start, end in zip(transitions[::2], transitions[1::2])
        )
    return tuple(spans)


def estimate_table_geometry(
    snapshot: AlignedRGBDSnapshot,
    mask: np.ndarray,
    calibration: RawServoCalibration,
    *,
    target_mask: np.ndarray | None = None,
) -> TableGeometry:
    calibration.validate_snapshot(snapshot)
    assert snapshot.depth_raw is not None
    assert snapshot.depth_scale_m is not None
    binary = _largest_filled_component(mask)
    if binary.shape != snapshot.depth_raw.shape:
        raise ValueError("table mask is not aligned to RGB-D")

    target_exclusion: np.ndarray | None = None
    if target_mask is not None:
        target_binary = np.asarray(target_mask, dtype=np.uint8)
        if target_binary.shape != binary.shape:
            raise ValueError("target mask is not aligned to RGB-D")
        exclusion_radius_px = 20
        exclusion_kernel = cv2.getStructuringElement(
            cv2.MORPH_ELLIPSE,
            (2 * exclusion_radius_px + 1, 2 * exclusion_radius_px + 1),
        )
        target_exclusion = cv2.dilate(
            target_binary,
            exclusion_kernel,
            iterations=1,
        )

    segments = _rgb_mask_line_segments(
        snapshot.rgb,
        binary,
        exclusion_mask=target_exclusion,
    )
    candidates = [
        segment
        for segment in segments
        if segment.length > _TABLE_EDGE_MIN_LENGTH_PX
    ]
    if not candidates:
        raise ValueError(
            "RGB edge and table mask intersection has no line longer than 45 px"
        )
    selected, sampled_pixels, sampled_depth_m = _select_nearest_pixel_segment(
        candidates,
        depth_raw=snapshot.depth_raw,
        depth_scale_m=snapshot.depth_scale_m,
    )

    sampled_u = sampled_pixels[:, 0].astype(np.float64)
    sampled_v = sampled_pixels[:, 1].astype(np.float64)
    camera = _deproject(
        sampled_u,
        sampled_v,
        sampled_depth_m,
        calibration,
    )
    camera_forward_left = np.column_stack((camera[:, 2], -camera[:, 0]))
    metric_line = _fit_tls_segment(camera_forward_left)
    center = metric_line.center
    direction = metric_line.direction.copy()
    if float(direction @ (camera_forward_left[-1] - camera_forward_left[0])) < 0.0:
        direction = -direction
    projection = (camera_forward_left - center) @ direction
    length = float(np.max(projection) - np.min(projection))
    normal = np.array([-direction[1], direction[0]])
    if float(normal @ center) < 0.0:
        normal = -normal
    yaw = math.atan2(float(normal[1]), float(normal[0]))
    endpoint_indices = (int(np.argmin(projection)), int(np.argmax(projection)))
    line_endpoints_xy_m = tuple(
        tuple(float(item) for item in center + projection[index] * direction)
        for index in endpoint_indices
    )
    line_endpoints_px = tuple(
        tuple(float(item) for item in sampled_pixels[index])
        for index in endpoint_indices
    )
    if line_endpoints_px[1] < line_endpoints_px[0]:
        line_endpoints_px = (line_endpoints_px[1], line_endpoints_px[0])
        line_endpoints_xy_m = (
            line_endpoints_xy_m[1],
            line_endpoints_xy_m[0],
        )
    return TableGeometry(
        yaw_error_rad=yaw,
        line_length_m=length,
        inlier_count=int(round(selected.length)) + 1,
        residual_m=metric_line.residual_median,
        line_center_xy_m=(float(center[0]), float(center[1])),
        line_endpoints_xy_m=line_endpoints_xy_m,
        line_endpoints_px=line_endpoints_px,
    )


class VisualServoController:
    """Bounded visibility-guarded phase controller."""

    def __init__(
        self,
        *,
        target_distance_m: float = 0.80,
        forward_tolerance_m: float = 0.10,
        lateral_tolerance_m: float = 0.10,
        command_ttl_s: float = 0.15,
        ema_alpha: float = 0.35,
        stable_frames: int = 5,
        missing_tolerance_frames: int = 30,
        max_run_s: float = 180.0,
        min_linear_speed_m_s: float = 0.40,
        max_lateral_speed_m_s: float = 0.40,
        min_yaw_speed_rad_s: float = 0.10,
        yaw_tolerance_deg: float = 8.0,
        yaw_coarse_speed_rad_s: float = 0.30,
        yaw_trim_speed_rad_s: float = 0.20,
        forward_recenter_yaw_speed_rad_s: float = 0.30,
        post_stop_sample_s: float = 0.0,
        allow_missing_table: bool = False,
        horizontal_guard_fraction: float = 0.25,
        horizontal_recovery_fraction: float = 0.30,
    ):
        self.target_distance_m = float(target_distance_m)
        self.forward_tolerance_m = float(forward_tolerance_m)
        self.lateral_tolerance_m = float(lateral_tolerance_m)
        if not all(
            math.isfinite(value) and value > 0.0
            for value in (self.forward_tolerance_m, self.lateral_tolerance_m)
        ):
            raise ValueError(
                "completion tolerances must be finite and positive"
            )
        self.command_ttl_s = float(command_ttl_s)
        self.ema_alpha = float(ema_alpha)
        self.stable_frames_required = int(stable_frames)
        self.missing_tolerance_frames = int(missing_tolerance_frames)
        self.max_run_s = float(max_run_s)
        guard_fraction = float(horizontal_guard_fraction)
        recovery_fraction = float(horizontal_recovery_fraction)
        if not (
            math.isfinite(guard_fraction)
            and math.isfinite(recovery_fraction)
            and 0.0 < guard_fraction < recovery_fraction < 0.5
        ):
            raise ValueError(
                "horizontal fractions must satisfy 0 < guard < recovery < 0.5"
            )
        lateral_speed_limit = float(max_lateral_speed_m_s)
        if not math.isfinite(lateral_speed_limit) or lateral_speed_limit <= 0.0:
            raise ValueError("maximum lateral speed must be finite and positive")
        min_linear_speed = float(min_linear_speed_m_s)
        if not math.isfinite(min_linear_speed) or min_linear_speed <= 0.0:
            raise ValueError("minimum linear speed must be finite and positive")
        yaw_coarse_speed = float(yaw_coarse_speed_rad_s)
        if not math.isfinite(yaw_coarse_speed) or yaw_coarse_speed <= 0.0:
            raise ValueError("coarse yaw speed must be finite and positive")
        yaw_trim_speed = float(yaw_trim_speed_rad_s)
        if not math.isfinite(yaw_trim_speed) or yaw_trim_speed <= 0.0:
            raise ValueError("trim yaw speed must be finite and positive")
        min_yaw_speed = float(min_yaw_speed_rad_s)
        if not math.isfinite(min_yaw_speed) or min_yaw_speed <= 0.0:
            raise ValueError("minimum yaw speed must be finite and positive")
        if min_yaw_speed > min(yaw_coarse_speed, yaw_trim_speed):
            raise ValueError(
                "minimum yaw speed must not exceed coarse or trim yaw speed"
            )
        yaw_tolerance = float(yaw_tolerance_deg)
        if (
            not math.isfinite(yaw_tolerance)
            or yaw_tolerance <= 0.0
            or yaw_tolerance > 180.0
        ):
            raise ValueError("yaw tolerance must be in (0, 180] degrees")
        forward_recenter_yaw_speed = float(forward_recenter_yaw_speed_rad_s)
        if (
            not math.isfinite(forward_recenter_yaw_speed)
            or forward_recenter_yaw_speed <= 0.0
        ):
            raise ValueError(
                "forward recenter yaw speed must be finite and positive"
            )
        post_stop_duration = float(post_stop_sample_s)
        if not math.isfinite(post_stop_duration) or post_stop_duration < 0.0:
            raise ValueError(
                "post-stop sampling duration must be finite and non-negative"
            )
        self.min_linear_speed_m_s = min_linear_speed
        self.max_lateral_speed_m_s = lateral_speed_limit
        self.min_yaw_speed_rad_s = min_yaw_speed
        self.yaw_tolerance_deg = yaw_tolerance
        self.yaw_tolerance_rad = math.radians(yaw_tolerance)
        self.yaw_coarse_speed_rad_s = yaw_coarse_speed
        self.yaw_trim_speed_rad_s = yaw_trim_speed
        self.allow_missing_table = bool(allow_missing_table)
        self.post_stop_sample_s = post_stop_duration
        self.guard_fraction = guard_fraction
        self.recovery_low_fraction = recovery_fraction
        self.recovery_high_fraction = 1.0 - recovery_fraction
        self.recenter_frames_required = 3
        self.forward_recenter_interval_s = 0.5
        self.forward_recenter_yaw_speed_rad_s = forward_recenter_yaw_speed
        self.yaw_lock_frames_required = 3
        self.orientation_stale_s = 0.25
        self.heading_setpoint_gain = 2.0
        self.reset(0.0)

    def reset(
        self,
        now: float,
        *,
        initial_phase: ServoPhase = ServoPhase.YAW_ALIGN,
    ) -> None:
        if initial_phase not in {
            ServoPhase.FORWARD_APPROACH,
            ServoPhase.VERTICAL_RECENTER,
            ServoPhase.YAW_ALIGN,
        }:
            raise ValueError(
                "initial servo phase must be forward_approach, "
                "vertical_recenter, or yaw_align"
            )
        self.start_time = float(now)
        self.last_update_time = float(now)
        self.filtered: np.ndarray | None = None
        self.current = ServoCommand(0.0, 0.0, 0.0, self.command_ttl_s)
        self.phase = initial_phase
        self.resume_phase: ServoPhase | None = None
        self.yaw_resume_phase: ServoPhase | None = None
        self.yaw_correction_context: str | None = None
        self.last_transition_reason: str | None = "reset"
        self.stable_frames = 0
        self.forward_approach_stable_frames = 0
        self.forward_recenter_next_calibration_at: float | None = None
        self.vertical_recenter_started_at: float | None = None
        self.vertical_recenter_elapsed_s = 0.0
        self.vertical_recenter_stable_frames = 0
        self.yaw_stable_frames = 0
        self.recenter_stable_frames = 0
        self.desired_heading_rad: float | None = None
        self.heading_setpoint_error_rad: float | None = None
        self.last_visual_yaw_error_rad: float | None = None
        self.yaw_error_trusted = False
        self.yaw_error_source = "unavailable"
        self.table_visible_last_update = False
        self.table_loss_alignment_done = False
        self.post_stop_started_at: float | None = None
        self.post_stop_elapsed_s = 0.0
        self.post_stop_sample_count = 0
        self.post_stop_valid_sample_count = 0
        self.post_stop_invalid_sample_count = 0
        self.invalid_frames = 0
        self.cumulative_translation_m = 0.0
        self.cumulative_yaw_rad = 0.0
        self.terminal_reason: str | None = None
        self.last_errors = (math.inf, math.inf, math.inf)

    @property
    def terminal(self) -> bool:
        return self.terminal_reason is not None

    @property
    def table_required(self) -> bool:
        if self.allow_missing_table:
            return False
        if self.phase is ServoPhase.POST_STOP_SAMPLING:
            return True
        visual_yaw_phases = {ServoPhase.YAW_ALIGN, ServoPhase.YAW_TRIM}
        if self.phase in visual_yaw_phases:
            return True
        if self.phase is ServoPhase.RECENTER:
            return self.resume_phase in visual_yaw_phases
        return False

    def _zero(self) -> ServoCommand:
        return ServoCommand(0.0, 0.0, 0.0, self.command_ttl_s)

    def _transition(self, phase: ServoPhase, reason: str) -> ServoCommand:
        self.phase = phase
        self.last_transition_reason = reason
        self.current = self._zero()
        self.stable_frames = 0
        if phase is not ServoPhase.RECENTER:
            self.recenter_stable_frames = 0
        if phase is not ServoPhase.FORWARD_APPROACH:
            self.forward_approach_stable_frames = 0
        if phase is not ServoPhase.FORWARD_RECENTER:
            self.forward_recenter_next_calibration_at = None
        if phase not in {
            ServoPhase.YAW_TRIM, ServoPhase.GLOBAL_YAW_ALIGN
        }:
            self.yaw_stable_frames = 0
        return self.current

    def _integrate(self, now: float) -> None:
        timestamp = float(now)
        dt = max(0.0, timestamp - self.last_update_time)
        self.cumulative_translation_m += math.hypot(self.current.vx, self.current.vy) * dt
        self.cumulative_yaw_rad += abs(self.current.wz) * dt
        self.last_update_time = timestamp

    def _stop(self, reason: str) -> ServoCommand:
        self.terminal_reason = reason
        if reason == "aligned":
            self.phase = ServoPhase.DONE
            self.last_transition_reason = "pose stable within eight degrees yaw"
        self.current = self._zero()
        return self.current


    def _begin_post_stop_sampling(self, now: float) -> ServoCommand:
        if self.post_stop_sample_s <= 0.0:
            return self._stop("aligned")
        self.post_stop_started_at = float(now)
        self.post_stop_elapsed_s = 0.0
        self.post_stop_sample_count = 0
        self.post_stop_valid_sample_count = 0
        self.post_stop_invalid_sample_count = 0
        return self._transition(
            ServoPhase.POST_STOP_SAMPLING,
            f"pose stable; sampling stopped pose for {self.post_stop_sample_s:g}s",
        )

    def _post_stop_sampling_complete(self, now: float) -> bool:
        if self.post_stop_started_at is None:
            return False
        self.post_stop_elapsed_s = max(
            0.0, float(now) - self.post_stop_started_at
        )
        if self.post_stop_elapsed_s + 1.0e-12 < self.post_stop_sample_s:
            return False
        self._stop("aligned")
        return True
    @staticmethod
    def _clip(value: float, limit: float) -> float:
        return max(-limit, min(limit, value))

    @staticmethod
    def _slew(previous: float, desired: float, delta: float) -> float:
        return previous + max(-delta, min(delta, desired - previous))

    @staticmethod
    def _wrapped_angle(value: float) -> float:
        return math.remainder(float(value), 2.0 * math.pi)

    def _orientation_headings(
        self, orientation: Mapping[str, Any] | None
    ) -> tuple[float, float] | None:
        if orientation is None:
            return None
        try:
            actual = float(orientation["actual_heading_rad"])
            setpoint = float(orientation["heading_setpoint_rad"])
        except (KeyError, TypeError, ValueError):
            return None
        if not math.isfinite(actual) or not math.isfinite(setpoint):
            return None
        for age_name in ("state_age_s", "telemetry_age_s"):
            raw_age = orientation.get(age_name)
            if raw_age is None:
                continue
            try:
                age = float(raw_age)
            except (TypeError, ValueError):
                return None
            if not math.isfinite(age) or age < 0.0 or age > self.orientation_stale_s:
                return None
        return self._wrapped_angle(actual), self._wrapped_angle(setpoint)

    def _propagate_yaw_error(
        self, orientation: Mapping[str, Any] | None
    ) -> float | None:
        headings = self._orientation_headings(orientation)
        if self.desired_heading_rad is None or headings is None:
            return None
        actual_heading, heading_setpoint = headings
        yaw_error = self._wrapped_angle(
            self.desired_heading_rad - actual_heading
        )
        self.heading_setpoint_error_rad = self._wrapped_angle(
            self.desired_heading_rad - heading_setpoint
        )
        self.yaw_error_source = "propagated_heading"
        self.yaw_error_trusted = True
        self.last_errors = (
            self.last_errors[0], self.last_errors[1], yaw_error
        )
        return yaw_error

    def _refresh_yaw_error(
        self,
        observation: RawServoObservation,
        visual_yaw_error: float,
        orientation: Mapping[str, Any] | None,
    ) -> tuple[float, bool]:
        headings = self._orientation_headings(orientation)
        table_was_visible = self.table_visible_last_update
        table_visible = observation.table is not None
        if table_visible:
            self.last_visual_yaw_error_rad = float(visual_yaw_error)
            self.table_visible_last_update = True
            self.table_loss_alignment_done = False
            if headings is not None:
                actual_heading, _ = headings
                self.desired_heading_rad = self._wrapped_angle(
                    actual_heading + visual_yaw_error
                )
        else:
            self.table_visible_last_update = False

        if (
            not table_visible
            and self.allow_missing_table
            and self.desired_heading_rad is None
            and self.last_visual_yaw_error_rad is not None
            and headings is not None
        ):
            actual_heading, _ = headings
            self.desired_heading_rad = self._wrapped_angle(
                actual_heading + self.last_visual_yaw_error_rad
            )

        if self.desired_heading_rad is not None and headings is not None:
            actual_heading, heading_setpoint = headings
            yaw_error = self._wrapped_angle(
                self.desired_heading_rad - actual_heading
            )
            self.heading_setpoint_error_rad = self._wrapped_angle(
                self.desired_heading_rad - heading_setpoint
            )
            if table_visible:
                self.yaw_error_source = "visual_calibrated_heading"
            elif self.allow_missing_table:
                # The relay setpoint can reach the target before the physical
                # base does, so missing-table fallback closes against the
                # measured heading rather than the commanded setpoint.
                self.heading_setpoint_error_rad = None
                self.yaw_error_source = "propagated_actual_heading"
            else:
                self.yaw_error_source = "propagated_heading"
            self.yaw_error_trusted = True
        elif table_visible:
            yaw_error = float(visual_yaw_error)
            self.heading_setpoint_error_rad = None
            self.yaw_error_source = "visual"
            self.yaw_error_trusted = True
        elif self.last_visual_yaw_error_rad is not None:
            yaw_error = self.last_visual_yaw_error_rad
            self.heading_setpoint_error_rad = None
            self.yaw_error_source = "held_visual_unpropagated"
            self.yaw_error_trusted = False
        else:
            yaw_error = math.inf
            self.heading_setpoint_error_rad = None
            self.yaw_error_source = "unavailable"
            self.yaw_error_trusted = False

        self.last_errors = (
            self.last_errors[0],
            self.last_errors[1],
            float(yaw_error),
        )
        return float(yaw_error), table_was_visible and not table_visible

    def _yaw_is_stable(self, yaw_error: float) -> bool:
        if (
            not self.yaw_error_trusted
            or abs(yaw_error) > self.yaw_tolerance_rad
        ):
            return False
        return (
            self.heading_setpoint_error_rad is None
            or abs(self.heading_setpoint_error_rad) <= self.yaw_tolerance_rad
        )

    def _yaw_command(self, *, speed_limit: float) -> ServoCommand:
        control_error = (
            self.last_errors[2]
            if self.heading_setpoint_error_rad is None
            else self.heading_setpoint_error_rad
        )
        if not self.yaw_error_trusted or not math.isfinite(control_error):
            self.current = self._zero()
            return self.current
        desired_wz = self._clip(
            self.heading_setpoint_gain * control_error
            if self.heading_setpoint_error_rad is not None
            else control_error,
            speed_limit,
        )
        if abs(control_error) <= math.radians(0.25):
            desired_wz = 0.0
        previous_wz = self.current.wz
        next_wz = self._clip(
            self._slew(previous_wz, desired_wz, 0.05), speed_limit
        )
        if 0.0 < abs(next_wz) < self.min_yaw_speed_rad_s:
            if desired_wz == 0.0 or previous_wz * desired_wz < 0.0:
                next_wz = 0.0
            else:
                next_wz = math.copysign(self.min_yaw_speed_rad_s, next_wz)
        self.current = ServoCommand(0.0, 0.0, next_wz, self.command_ttl_s)
        return self.current

    def _begin_global_yaw(
        self, *, context: str, resume_phase: ServoPhase
    ) -> ServoCommand:
        self.yaw_resume_phase = resume_phase
        self.yaw_correction_context = context
        self.yaw_stable_frames = 0
        self._transition(ServoPhase.GLOBAL_YAW_ALIGN, context)
        return self._yaw_command(speed_limit=self.yaw_trim_speed_rad_s)

    def _enforce_min_linear_speed(
        self, vx: float, vy: float
    ) -> tuple[float, float]:
        speed = math.hypot(vx, vy)
        if speed == 0.0 or speed >= self.min_linear_speed_m_s:
            return vx, vy
        strict_minimum = math.nextafter(self.min_linear_speed_m_s, math.inf)
        scale = strict_minimum / speed
        return vx * scale, vy * scale

    def stop_if_timed_out(self, *, now: float) -> bool:
        if self.terminal:
            return True
        self._integrate(now)
        if self.phase is ServoPhase.POST_STOP_SAMPLING:
            self._post_stop_sampling_complete(now)
            return self.terminal
        if self.phase is ServoPhase.VERTICAL_RECENTER:
            self._vertical_recenter_timed_out(now)
            return self.terminal
        self._check_limits(now)
        return self.terminal

    def _check_limits(self, now: float) -> ServoCommand | None:
        if self.phase is ServoPhase.POST_STOP_SAMPLING:
            return None
        if float(now) - self.start_time >= self.max_run_s:
            return self._stop("maximum run time reached")
        return None

    def _visibility_guarded(self, observation: RawServoObservation) -> bool:
        width = float(observation.image_width)
        if width <= 0.0:
            return True
        x1, _, x2, _ = observation.target_bbox_xyxy
        center = 0.5 * (x1 + x2)
        return (
            center < self.guard_fraction * width
            or center > (1.0 - self.guard_fraction) * width
        )

    def _target_center_recovered(self, observation: RawServoObservation) -> bool:
        width = float(observation.image_width)
        if width <= 0.0:
            return False
        x1, _, x2, _ = observation.target_bbox_xyxy
        center = 0.5 * (x1 + x2)
        return self.recovery_low_fraction * width <= center <= self.recovery_high_fraction * width

    @staticmethod
    def _vertical_height_from_bottom(
        observation: RawServoObservation,
    ) -> float | None:
        height = float(observation.image_height)
        if height <= 0.0:
            return None
        _, y1, _, y2 = observation.target_bbox_xyxy
        center_y = 0.5 * (y1 + y2)
        return 1.0 - center_y / height

    @staticmethod
    def _vertical_bottom_fraction(
        observation: RawServoObservation,
    ) -> float | None:
        height = float(observation.image_height)
        if height <= 0.0:
            return None
        _, _, _, y2 = observation.target_bbox_xyxy
        return float(y2) / height

    def _vertical_recenter_timed_out(self, now: float) -> bool:
        started_at = self.vertical_recenter_started_at
        if started_at is None:
            return False
        self.vertical_recenter_elapsed_s = max(
            0.0, float(now) - started_at
        )
        if self.vertical_recenter_elapsed_s < 0.7:
            return False
        self._transition(
            ServoPhase.YAW_ALIGN,
            "vertical recenter completed after 0.7 seconds",
        )
        return True

    def _vertical_recenter_command(self) -> ServoCommand:
        return ServoCommand(
            self.min_linear_speed_m_s,
            0.0,
            0.0,
            self.command_ttl_s,
        )

    def _update_vertical_recenter(
        self,
        observation: RawServoObservation,
        *,
        now: float,
    ) -> ServoCommand:
        height_from_bottom = self._vertical_height_from_bottom(observation)
        if self.vertical_recenter_started_at is None:
            if (
                height_from_bottom is None
                or height_from_bottom <= 0.90
            ):
                return self._transition(
                    ServoPhase.YAW_ALIGN,
                    "vertical recenter not required after chest-to-head switch",
                )
            self.vertical_recenter_started_at = float(now)
            self.vertical_recenter_elapsed_s = 0.0
        elif self._vertical_recenter_timed_out(now):
            return self.current

        bottom_fraction = self._vertical_bottom_fraction(observation)
        if bottom_fraction is not None and bottom_fraction >= 0.80:
            self.vertical_recenter_stable_frames = 1
            return self._transition(
                ServoPhase.YAW_ALIGN,
                "target box bottom reached 80 percent image height",
            )
        self.vertical_recenter_stable_frames = 0

        self.invalid_frames = 0
        self.current = self._vertical_recenter_command()
        return self.current

    def _forward_approach_vx(self, forward_error: float) -> float:
        if forward_error <= self.forward_tolerance_m + 1.0e-12:
            return 0.0
        desired_vx = self._clip(0.5 * forward_error, 0.20)
        vx, _ = self._enforce_min_linear_speed(desired_vx, 0.0)
        return vx

    def _update_forward_recenter(
        self,
        observation: RawServoObservation,
        *,
        now: float,
    ) -> ServoCommand:
        """Sample-and-hold basket centering used only by chest forward approach."""
        vx = self._forward_approach_vx(self.last_errors[0])
        next_calibration = self.forward_recenter_next_calibration_at
        if next_calibration is not None and float(now) < next_calibration:
            self.current = ServoCommand(
                vx, 0.0, self.current.wz, self.command_ttl_s
            )
            return self.current

        self.forward_recenter_next_calibration_at = (
            float(now) + self.forward_recenter_interval_s
        )
        if self._target_center_recovered(observation):
            self.resume_phase = None
            return self._transition(
                ServoPhase.FORWARD_APPROACH,
                "basket rotation-recentered during forward approach",
            )

        width = float(observation.image_width)
        if width <= 0.0:
            self.current = self._zero()
            return self.current
        x1, _, x2, _ = observation.target_bbox_xyxy
        target_center_x = 0.5 * (x1 + x2)
        image_center_x = 0.5 * width
        if target_center_x == image_center_x:
            self.current = self._zero()
            return self.current
        # Positive wz turns the camera view toward a target on the image's left.
        direction = 1.0 if target_center_x < image_center_x else -1.0
        self.current = ServoCommand(
            vx,
            0.0,
            direction * self.forward_recenter_yaw_speed_rad_s,
            self.command_ttl_s,
        )
        return self.current

    def _update_filter(self, observation: RawServoObservation) -> tuple[float, float, float]:
        raw_target = (observation.target.forward_m, observation.target.right_m)
        yaw_sample = (
            observation.table.yaw_error_rad
            if observation.table is not None
            else (0.0 if self.filtered is None else float(self.filtered[2]))
        )
        sample = np.array([raw_target[0], raw_target[1], yaw_sample], dtype=np.float64)
        if self.filtered is None:
            self.filtered = sample
        else:
            self.filtered[:2] = (
                self.ema_alpha * sample[:2]
                + (1.0 - self.ema_alpha) * self.filtered[:2]
            )
            if observation.table is not None:
                self.filtered[2] = (
                    self.ema_alpha * sample[2]
                    + (1.0 - self.ema_alpha) * self.filtered[2]
                )
        errors = (
            float(self.filtered[0] - self.target_distance_m),
            float(self.filtered[1]),
            float(self.filtered[2]),
        )
        self.last_errors = errors
        return errors

    def update(
        self,
        observation: RawServoObservation,
        *,
        now: float,
        orientation: Mapping[str, Any] | None = None,
    ) -> ServoCommand:
        if self.terminal:
            return self.current
        self.last_transition_reason = None
        self._integrate(now)
        limited = self._check_limits(now)
        if limited is not None:
            return limited
        if self.phase is ServoPhase.VERTICAL_RECENTER:
            return self._update_vertical_recenter(observation, now=now)
        forward_error, right_error, visual_yaw_error = self._update_filter(
            observation
        )
        yaw_error, table_lost = self._refresh_yaw_error(
            observation, visual_yaw_error, orientation
        )


        if self.phase is ServoPhase.POST_STOP_SAMPLING:
            self.invalid_frames = 0
            self.post_stop_sample_count += 1
            self.post_stop_valid_sample_count += 1
            self.current = self._zero()
            self._post_stop_sampling_complete(now)
            return self.current
        if self.phase is ServoPhase.GLOBAL_YAW_ALIGN:
            self.invalid_frames = 0
            stable_yaw = self._yaw_is_stable(yaw_error)
            self.yaw_stable_frames = (
                self.yaw_stable_frames + 1 if stable_yaw else 0
            )
            if stable_yaw:
                self.current = self._zero()
                if self.yaw_stable_frames >= self.yaw_lock_frames_required:
                    context = self.yaw_correction_context or "global yaw correction"
                    resume = self.yaw_resume_phase or ServoPhase.TRANSLATE_TARGET
                    if not self.table_visible_last_update:
                        self.table_loss_alignment_done = True
                    self.yaw_resume_phase = None
                    self.yaw_correction_context = None
                    return self._transition(
                        resume,
                        f"{context} aligned within "
                        f"{self.yaw_tolerance_deg:g} degrees",
                    )
                return self.current
            if not self.yaw_error_trusted:
                return self.note_invalid(
                    "orientation telemetry unavailable for global yaw",
                    hard=False,
                    now=now,
                    integrated=True,
                    orientation=orientation,
                )
            return self._yaw_command(speed_limit=self.yaw_trim_speed_rad_s)

        if self.phase is ServoPhase.FORWARD_APPROACH:
            if self._visibility_guarded(observation):
                self.resume_phase = ServoPhase.FORWARD_APPROACH
                self.invalid_frames = 0
                self._transition(
                    ServoPhase.FORWARD_RECENTER,
                    "target visibility guard during forward approach",
                )
                return self._update_forward_recenter(observation, now=now)
            self.invalid_frames = 0
            forward_reached = (
                forward_error <= self.forward_tolerance_m + 1.0e-12
            )
            self.forward_approach_stable_frames = (
                self.forward_approach_stable_frames + 1
                if forward_reached
                else 0
            )
            if forward_reached:
                self.current = self._zero()
                if (
                    self.forward_approach_stable_frames
                    < self.recenter_frames_required
                ):
                    return self.current
                return self._transition(
                    ServoPhase.YAW_ALIGN,
                    "chest-camera forward error reduced before yaw",
                )
            vx = self._forward_approach_vx(forward_error)
            self.current = ServoCommand(vx, 0.0, 0.0, self.command_ttl_s)
            return self.current

        if self.phase is ServoPhase.FORWARD_RECENTER:
            self.invalid_frames = 0
            return self._update_forward_recenter(observation, now=now)

        if self.phase in {ServoPhase.YAW_ALIGN, ServoPhase.YAW_TRIM}:
            if self._visibility_guarded(observation):
                self.resume_phase = self.phase
                self.invalid_frames = 0
                return self._transition(
                    ServoPhase.RECENTER, "target visibility guard"
                )
            if observation.table is None and not self.allow_missing_table:
                return self.note_invalid(
                    "missing table geometry",
                    hard=False,
                    now=now,
                    integrated=True,
                    orientation=orientation,
                )
            self.invalid_frames = 0
            if (
                self.phase is ServoPhase.YAW_ALIGN
                and abs(yaw_error) <= self.yaw_tolerance_rad
            ):
                self._transition(
                    ServoPhase.YAW_TRIM,
                    f"coarse yaw within {self.yaw_tolerance_deg:g} degrees",
                )

        if self.phase is ServoPhase.RECENTER:
            self.invalid_frames = 0
            recovered = self._target_center_recovered(observation)
            self.recenter_stable_frames = (
                self.recenter_stable_frames + 1 if recovered else 0
            )
            if self.recenter_stable_frames >= self.recenter_frames_required:
                resume = self.resume_phase or ServoPhase.YAW_ALIGN
                if (
                    observation.table is None
                    and not self.allow_missing_table
                    and resume in {
                        ServoPhase.YAW_ALIGN,
                        ServoPhase.YAW_TRIM,
                    }
                ):
                    return self.note_invalid(
                        "missing table geometry after recenter",
                        hard=False,
                        now=now,
                        integrated=True,
                        orientation=orientation,
                    )
                self.resume_phase = None
                return self._transition(resume, "target recentered")
            controlled_right = 0.0 if abs(right_error) <= 0.03 else right_error
            desired_vy = self._clip(
                -0.6 * controlled_right, self.max_lateral_speed_m_s
            )
            vx, vy = self._enforce_min_linear_speed(0.0, desired_vy)
            self.current = ServoCommand(vx, vy, 0.0, self.command_ttl_s)
            return self.current

        if self.phase is ServoPhase.YAW_TRIM:
            stable_yaw = self._yaw_is_stable(yaw_error)
            self.yaw_stable_frames = (
                self.yaw_stable_frames + 1 if stable_yaw else 0
            )
            if stable_yaw:
                self.current = self._zero()
                if self.yaw_stable_frames >= self.yaw_lock_frames_required:
                    return self._transition(
                        ServoPhase.TRANSLATE_TARGET,
                        "closed-loop yaw stable within "
                        f"{self.yaw_tolerance_deg:g} degrees",
                    )
                return self.current
            return self._yaw_command(speed_limit=self.yaw_trim_speed_rad_s)

        if self.phase is ServoPhase.YAW_ALIGN:
            return self._yaw_command(speed_limit=self.yaw_coarse_speed_rad_s)

        if self.phase is ServoPhase.TRANSLATE_TARGET:
            self.invalid_frames = 0
            if table_lost and not self.table_loss_alignment_done:
                return self._begin_global_yaw(
                    context="last tracked table yaw",
                    resume_phase=ServoPhase.TRANSLATE_TARGET,
                )

            forward_stable = (
                abs(forward_error) <= self.forward_tolerance_m + 1.0e-12
            )
            lateral_stable = (
                abs(right_error) <= self.lateral_tolerance_m + 1.0e-12
            )
            position_stable = forward_stable and lateral_stable
            yaw_stable = self._yaw_is_stable(yaw_error)
            completion_stable = position_stable and yaw_stable
            self.stable_frames = (
                self.stable_frames + 1 if completion_stable else 0
            )
            if position_stable:
                self.current = self._zero()
                if not yaw_stable:
                    return self._begin_global_yaw(
                        context="final yaw",
                        resume_phase=ServoPhase.TRANSLATE_TARGET,
                    )
                if self.stable_frames < self.stable_frames_required:
                    return self.current
                return self._begin_post_stop_sampling(now)

            # Keep translation axis-aligned: center the target laterally before
            # changing standoff distance. Sending vx and vy together produces
            # poor diagonal steps on the physical robot.
            if not lateral_stable:
                desired_vx = 0.0
                desired_vy = self._clip(
                    -0.6 * right_error, self.max_lateral_speed_m_s
                )
            else:
                desired_vx = self._clip(0.5 * forward_error, 0.20)
                desired_vy = 0.0
            vx, vy = self._enforce_min_linear_speed(desired_vx, desired_vy)
            self.current = ServoCommand(vx, vy, 0.0, self.command_ttl_s)
            return self.current

        return self.current

    def note_invalid(
        self,
        reason: str,
        *,
        hard: bool,
        now: float,
        integrated: bool = False,
        orientation: Mapping[str, Any] | None = None,
    ) -> ServoCommand:
        if self.terminal:
            return self.current
        if not integrated:
            self._integrate(now)
        self._propagate_yaw_error(orientation)
        if self.phase is ServoPhase.POST_STOP_SAMPLING:
            self.current = self._zero()
            self.invalid_frames += 1
            self.post_stop_sample_count += 1
            self.post_stop_invalid_sample_count += 1
            self._post_stop_sampling_complete(now)
            return self.current
        limited = self._check_limits(now)
        if limited is not None:
            return limited
        if self.phase is ServoPhase.VERTICAL_RECENTER:
            self.vertical_recenter_stable_frames = 0
            self.invalid_frames = 0
            if self._vertical_recenter_timed_out(now):
                return self.current
            self.current = self._vertical_recenter_command()
            return self.current
        self.stable_frames = 0
        self.forward_approach_stable_frames = 0
        self.forward_recenter_next_calibration_at = None
        self.yaw_stable_frames = 0
        self.current = self._zero()
        if hard:
            return self._stop(reason)
        self.invalid_frames += 1
        if self.invalid_frames >= self.missing_tolerance_frames:
            return self._stop(f"tracking lost: {reason}")
        return self.current

def build_servo_velocity_message(
    command: ServoCommand,
    *,
    action: str,
    camera_stream: str | None = None,
    viewer_target_bbox_xyxy: Sequence[float] | None = None,
    viewer_target_lateral_anchor_px: Sequence[float] | None = None,
    viewer_table_edge_endpoints_px: Sequence[Sequence[float]] | None = None,
    viewer_desk_mask_row_spans: Sequence[Sequence[int]] | None = None,
    viewer_image_size: tuple[int, int] | None = None,
) -> str:
    payload = {
        "action": action,
        "angle_rad": abs(command.wz) * command.duration,
        "distance_m": math.hypot(command.vx, command.vy) * command.duration,
        "duration_s": command.duration,
        "raw_text": "raw YOLOE visual servo",
        "segments": [
            {
                "duration_s": command.duration,
                "vx": command.vx,
                "vy": command.vy,
                "wz": command.wz,
            }
        ],
        "source": "base_pose",
        "status": "ok",
        "type": "navila_reasan_velocity_command",
        "velocity": {"vx": command.vx, "vy": command.vy, "wz": command.wz},
        "version": 1,
    }
    if camera_stream:
        payload["camera_stream"] = str(camera_stream)
    if viewer_target_bbox_xyxy is not None:
        overlay: dict[str, Any] = {
            "target_bbox_xyxy": [
                float(value) for value in viewer_target_bbox_xyxy
            ],
        }
        if viewer_target_lateral_anchor_px is not None:
            overlay["target_lateral_anchor_px"] = [
                float(value) for value in viewer_target_lateral_anchor_px
            ]
        if viewer_table_edge_endpoints_px is not None:
            overlay["table_edge_endpoints_px"] = [
                [float(value) for value in point]
                for point in viewer_table_edge_endpoints_px
            ]
        if viewer_desk_mask_row_spans:
            overlay["desk_mask_row_spans"] = [
                [int(value) for value in span]
                for span in viewer_desk_mask_row_spans
            ]
        if viewer_image_size is not None:
            overlay["image_size"] = [
                int(viewer_image_size[0]),
                int(viewer_image_size[1]),
            ]
        payload["viewer_overlay"] = overlay
    return json.dumps(payload, separators=(",", ":"))


class GenerationGate:
    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._active: int | None = None

    def activate(self, generation: int) -> None:
        with self._lock:
            self._active = generation

    def cancel(self, generation: int | None = None) -> None:
        with self._lock:
            if generation is None or self._active == generation:
                self._active = None

    def is_active(self, generation: int) -> bool:
        with self._lock:
            return self._active == generation


def _route_worker_event(
    events: queue.Queue[RawServoEvent],
    observation_events: queue.Queue[RawServoEvent] | None,
    item: RawServoEvent,
) -> RawServoEvent | None:
    if item.kind != "observation" or observation_events is None:
        events.put(item)
        return None
    try:
        observation_events.put_nowait(item)
        return None
    except queue.Full:
        try:
            displaced = observation_events.get_nowait()
        except queue.Empty:
            displaced = None
        observation_events.put_nowait(item)
        return displaced


def _submit_diagnostic_decision(
    diagnostics: AsyncFrameDiagnosticsWriter | None,
    event: RawServoEvent,
    *,
    control_applied: bool,
    controller_state: Mapping[str, Any] | None = None,
    command: Mapping[str, Any] | None = None,
    orientation: Mapping[str, Any] | None = None,
) -> None:
    if diagnostics is None or event.frame is None:
        return
    try:
        diagnostics.submit_decision(
            event.generation,
            event.frame.frame_index,
            control_applied=control_applied,
            controller_state=controller_state,
            command=command,
            orientation=orientation,
        )
    except Exception as exc:
        diagnostics.logger(f"[RawServo] WARNING diagnostic submit failed: {exc}")


def _publish_worker_event(
    events: queue.Queue[RawServoEvent],
    observation_events: queue.Queue[RawServoEvent] | None,
    diagnostics: AsyncFrameDiagnosticsWriter | None,
    item: RawServoEvent,
) -> RawServoEvent | None:
    if (
        diagnostics is not None
        and item.frame is not None
        and item.output_dir is not None
    ):
        try:
            diagnostics.submit_frame(item.generation, item.output_dir, item.frame)
        except Exception as exc:
            diagnostics.logger(f"[RawServo] WARNING diagnostic submit failed: {exc}")
    item = replace(item, produced_at_monotonic=time.monotonic())
    displaced = _route_worker_event(events, observation_events, item)
    if displaced is not None:
        _submit_diagnostic_decision(
            diagnostics,
            displaced,
            control_applied=False,
        )
    return displaced


def _save_png(path: Path, image: np.ndarray, *, rgb: bool = False) -> None:
    value = cv2.cvtColor(image, cv2.COLOR_RGB2BGR) if rgb else image
    ok, encoded = cv2.imencode(".png", value)
    if not ok:
        raise OSError(f"failed to encode {path.name}")
    _atomic_write_bytes(path, encoded.tobytes())


