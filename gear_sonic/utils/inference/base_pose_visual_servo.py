def ground_raw_servo_references(
    config: Any,
    rgb_path: str | Path,
    output_dir: str | Path,
    *,
    client_factory: Callable[[], Any] | None = None,
    calibration: RawServoCalibration | None = None,
) -> tuple[
    RawServoTargetSpec,
    tuple[tuple[float, float, float, float], ...],
]:
    image_path = Path(rgb_path).resolve()
    workdir = Path(output_dir).resolve()
    target_prompt = build_raw_servo_target_prompt(
        config.task,
        calibration if calibration is not None else calibration_from_config(config),
    )
    table_prompt = build_raw_servo_table_prompt()
    _write_text(workdir / "target_prompt.txt", target_prompt)
    _write_text(workdir / "table_prompt.txt", table_prompt)

    def make_client() -> Any:
        if client_factory is not None:
            return client_factory()
        return _client_from_config(config)

    def run_target() -> RawServoTargetSpec:
        raw_target = make_client().run(
            prompt=target_prompt,
            image_paths=[image_path],
            schema=RAW_SERVO_TARGET_SCHEMA,
            schema_filename="target_schema.json",
            cwd=workdir,
        )
        _write_json(workdir / "target_result.json", raw_target)
        return validate_raw_servo_target(raw_target)

    def run_table() -> tuple[tuple[float, float, float, float], ...]:
        raw_table = make_client().run(
            prompt=table_prompt,
            image_paths=[image_path],
            schema=GROUNDING_SCHEMA,
            schema_filename="table_schema.json",
            cwd=workdir,
        )
        _write_json(workdir / "table_result.json", raw_table)
        return validate_raw_servo_table(raw_table)

    with ThreadPoolExecutor(
        max_workers=2, thread_name_prefix="raw-servo-grounding"
    ) as pool:
        target_future = pool.submit(run_target)
        table_future = pool.submit(run_table)
        return target_future.result(), table_future.result()


def _best_tracked_instance(
    instances: Sequence[TrackedInstance],
    class_index: int,
) -> TrackedInstance | None:
    candidates = [item for item in instances if item.class_index == class_index]
    if not candidates:
        return None
    return max(candidates, key=lambda item: item.confidence)


def _resolve_target(
    instances: list[TrackedInstance],
    expected_id: int,
    class_index: int = 0,
) -> tuple[TrackedInstance | None, bool, bool]:
    candidates = [item for item in instances if item.class_index == class_index]
    for item in candidates:
        if item.track_id == expected_id:
            return item, False, False
    if candidates:
        return max(candidates, key=lambda item: item.confidence), True, False
    wrong_class = any(item.track_id == expected_id for item in instances)
    return None, False, wrong_class


def _observation(
    snapshot: AlignedRGBDSnapshot,
    target: TrackedInstance,
    surface: TrackedInstance | None,
    calibration: RawServoCalibration,
) -> RawServoObservation:
    table = None
    table_error = None
    desk_mask = None
    if surface is not None:
        desk_mask = _largest_filled_component(surface.mask)
        try:
            table = estimate_table_geometry(
                snapshot,
                desk_mask,
                calibration,
                target_mask=target.mask,
            )
        except ValueError as exc:
            table = None
            table_error = str(exc)
    return RawServoObservation(
        target=estimate_target_geometry(
            snapshot,
            target.mask,
            calibration,
            bbox_xyxy=target.bbox_xyxy,
        ),
        table=table,
        camera_timestamp=snapshot.timestamp,
        target_track_id=target.track_id,
        surface_track_id=None if surface is None else surface.track_id,
        target_bbox_xyxy=target.bbox_xyxy,
        image_width=int(snapshot.rgb.shape[1]),
        image_height=int(snapshot.rgb.shape[0]),
        table_geometry_error=table_error,
        desk_mask=desk_mask,
    )



def _diagnostic_frame(
    frame_index: int,
    snapshot: AlignedRGBDSnapshot,
    target: TrackedInstance | None,
    surface: TrackedInstance | None,
    observation: RawServoObservation | None,
    *,
    kind: str,
    error: str | None = None,
    camera_stream: str | None = None,
    attempt_id: int | None = None,
    failover_stage: str | None = None,
    reference_source_stream: str | None = None,
    reference_kind: str | None = None,
    prompt_mode: str | None = None,
) -> DetectionFrameData:
    target_geometry = None
    table_geometry = None
    if observation is not None:
        target_geometry = {
            "forward_m": observation.target.forward_m,
            "right_m": observation.target.right_m,
            "body_xyz_m": list(observation.target.body_xyz_m),
            "valid_depth_pixels": observation.target.valid_depth_pixels,
            "valid_ratio": observation.target.valid_ratio,
            "median_depth_m": observation.target.median_depth_m,
            "lateral_anchor_px": (
                None
                if observation.target.lateral_anchor_px is None
                else list(observation.target.lateral_anchor_px)
            ),
        }
        if observation.table is not None:
            table_geometry = {
                "yaw_error_rad": observation.table.yaw_error_rad,
                "line_length_m": observation.table.line_length_m,
                "inlier_count": observation.table.inlier_count,
                "residual_m": observation.table.residual_m,
                "line_center_xy_m": list(observation.table.line_center_xy_m),
                "line_endpoints_xy_m": (
                    None
                    if observation.table.line_endpoints_xy_m is None
                    else [
                        list(point)
                        for point in observation.table.line_endpoints_xy_m
                    ]
                ),
                "line_endpoints_px": (
                    None
                    if observation.table.line_endpoints_px is None
                    else [
                        list(point) for point in observation.table.line_endpoints_px
                    ]
                ),
            }
    return DetectionFrameData(
        frame_index=frame_index,
        camera_timestamp=snapshot.timestamp,
        rgb=snapshot.rgb.copy(),
        camera_stream=camera_stream,
        attempt_id=attempt_id,
        failover_stage=failover_stage,
        reference_source_stream=reference_source_stream,
        reference_kind=reference_kind,
        prompt_mode=prompt_mode,
        target_bbox_xyxy=None if target is None else target.bbox_xyxy,
        target_mask=None if target is None else target.mask.copy(),
        target_track_id=None if target is None else target.track_id,
        target_confidence=None if target is None else target.confidence,
        surface_bbox_xyxy=None if surface is None else surface.bbox_xyxy,
        surface_mask=None if surface is None else surface.mask.copy(),
        completed_surface_mask=(
            None
            if observation is None or observation.desk_mask is None
            else observation.desk_mask.copy()
        ),
        surface_track_id=None if surface is None else surface.track_id,
        surface_confidence=None if surface is None else surface.confidence,
        target_geometry=target_geometry,
        table_geometry=table_geometry,
        table_geometry_error=(
            None if observation is None else observation.table_geometry_error
        ),
        perception_kind=kind,
        perception_error=error,
    )


def run_raw_servo_worker(
    config: Any,
    requests: queue.Queue[int | None],
    events: queue.Queue[RawServoEvent],
    gate: GenerationGate,
    stop_event: threading.Event,
    *,
    observation_events: queue.Queue[RawServoEvent] | None = None,
    diagnostics: AsyncFrameDiagnosticsWriter | None = None,
    camera_factory: Callable[[], AlignedRGBDCamera] | None = None,
    client_factory: Callable[[], Any] | None = None,
    tracker_factory: Callable[[], Any] | None = None,
    reference_updater_factory: Callable[[], Any] | None = None,
    table_required: Callable[[], bool] | None = None,
) -> None:
    calibration = calibration_from_config(config)
    camera: AlignedRGBDCamera | None = None
    tracker: Any | None = None
    reference_updater: Any | None = None
    try:
        while not stop_event.is_set():
            try:
                generation = requests.get(timeout=0.1)
            except queue.Empty:
                continue
            if generation is None or stop_event.is_set():
                return
            output_dir: Path | None = None
            try:
                if camera is None:
                    camera = (
                        camera_factory()
                        if camera_factory is not None
                        else AlignedRGBDCamera(
                            config.camera_host,
                            config.camera_port,
                            stream_name=config.camera_stream,
                            require_depth=True,
                            required_depth_source=None,
                            timeout_ms=config.camera_timeout_ms,
                            calibration_path=config.camera_intrinsics_path,
                        )
                    )
                snapshot = camera.capture()
                calibration.validate_snapshot(snapshot)
                stamp = time.strftime("%Y%m%d_%H%M%S")
                output_dir = (
                    Path(config.output_root).resolve()
                    / f"raw_yoloe_{stamp}_g{generation}"
                )
                output_dir.mkdir(parents=True, exist_ok=False)
                rgb_path = output_dir / "initial_rgb.png"
                _save_png(rgb_path, snapshot.rgb, rgb=True)
                assert snapshot.depth_raw is not None
                _save_png(output_dir / "initial_depth_raw.png", snapshot.depth_raw)
                spec, table_bboxes = ground_raw_servo_references(
                    config,
                    rgb_path,
                    output_dir,
                    client_factory=client_factory,
                )
                if not gate.is_active(generation):
                    continue
                if reference_updater is None:
                    if reference_updater_factory is not None:
                        reference_updater = reference_updater_factory()
                    elif (
                        getattr(config, "raw_reference_update_interval_frames", 5) > 0
                        and tracker_factory is None
                    ):
                        reference_updater = AsyncTargetReferenceUpdater(
                            lambda: YoloeTargetReferenceEncoder(
                                config.raw_yoloe_model_path,
                                confidence=config.raw_yoloe_confidence,
                                imgsz=config.raw_yoloe_imgsz,
                                device=config.raw_yoloe_device,
                            ),
                            min_confidence=config.raw_reference_update_min_confidence,
                            min_iou=config.raw_reference_update_min_iou,
                        )
                if tracker is None:
                    tracker = (
                        tracker_factory()
                        if tracker_factory
                        else YoloePersistentTracker(
                            config.raw_yoloe_model_path,
                            confidence=config.raw_yoloe_confidence,
                            imgsz=config.raw_yoloe_imgsz,
                            device=config.raw_yoloe_device,
                        )
                    )
                reference_update_gate = (
                    TargetReferenceUpdateGate(
                        interval_frames=config.raw_reference_update_interval_frames,
                        min_confidence=config.raw_reference_update_min_confidence,
                    )
                    if reference_updater is not None
                    else None
                )
                visual_prompt = tracker.start(
                    snapshot.rgb,
                    target_prompt=spec.target_prompt,
                    target_bbox=spec.target_bbox,
                    surface_prompt="desk",
                    surface_bboxes=table_bboxes,
                )
                _write_json(output_dir / "yoloe_reference_prompt.json", visual_prompt)
                instances = tracker.track(snapshot.rgb)
                target = select_initial_instance(
                    instances,
                    class_index=0,
                    grounded_bboxes=(spec.target_bbox,),
                    width=calibration.width,
                    height=calibration.height,
                )
                surface = select_initial_instance(
                    instances,
                    class_index=1,
                    grounded_bboxes=table_bboxes,
                    width=calibration.width,
                    height=calibration.height,
                )
                observation = _observation(snapshot, target, surface, calibration)
                frame_index = 0
                _write_json(
                    output_dir / "tracking_ids.json",
                    {
                        "target_track_id": target.track_id,
                        "surface_track_id": surface.track_id,
                        "target_prompt": spec.target_prompt,
                        "surface_prompt": "desk",
                        "table_bboxes": [list(bbox) for bbox in table_bboxes],
                        "reference_boxes_xyxy": visual_prompt[
                            "reference_boxes_xyxy"
                        ],
                    },
                )
                _publish_worker_event(
                    events, observation_events, diagnostics,
                    RawServoEvent(
                        generation,
                        "initialized",
                        observation=observation,
                        output_dir=str(output_dir),
                        details={
                            "target_prompt": spec.target_prompt,
                            "surface_prompt": "desk",
                            "table_bboxes": [list(bbox) for bbox in table_bboxes],
                            "reference_boxes_xyxy": visual_prompt[
                                "reference_boxes_xyxy"
                            ],
                            "target_track_id": target.track_id,
                            "surface_track_id": surface.track_id,
                        },
                        frame=_diagnostic_frame(
                            frame_index,
                            snapshot,
                            target,
                            surface,
                            observation,
                            kind="initialized",
                        ),
                    ),
                )
                target_id, surface_id = target.track_id, surface.track_id
                visual_missing_frames = 0
                text_recovery_missing_frames = 0
                text_recovery_active = False

                def begin_text_recovery(source_frame: int) -> None:
                    nonlocal text_recovery_active
                    nonlocal text_recovery_missing_frames
                    nonlocal visual_missing_frames
                    nonlocal target_id, surface_id
                    text_artifact = tracker.start_all_text(
                        target_prompt=SINGLE_CAMERA_TEXT_TARGET_PROMPT,
                        surface_prompt=SINGLE_CAMERA_TEXT_SURFACE_PROMPT,
                    )
                    _write_json(
                        output_dir
                        / (
                            "yoloe_text_recovery_prompt_"
                            f"{source_frame:06d}.json"
                        ),
                        text_artifact,
                    )
                    text_recovery_active = True
                    text_recovery_missing_frames = 0
                    visual_missing_frames = 0
                    target_id = None
                    surface_id = None
                next_frame = time.monotonic()
                while gate.is_active(generation) and not stop_event.is_set():
                    delay = next_frame - time.monotonic()
                    if delay > 0.0:
                        stop_event.wait(min(delay, 0.05))
                        continue
                    next_frame = time.monotonic() + 1.0 / config.raw_servo_hz
                    snapshot = camera.capture()
                    frame_index += 1
                    try:
                        calibration.validate_snapshot(snapshot)
                    except BasePoseCameraError as exc:
                        _publish_worker_event(
                            events, observation_events, diagnostics,
                            RawServoEvent(
                                generation,
                                "invalid",
                                output_dir=str(output_dir),
                                error=str(exc),
                                hard=True,
                                frame=_diagnostic_frame(
                                    frame_index,
                                    snapshot,
                                    None,
                                    None,
                                    None,
                                    kind="invalid",
                                    error=str(exc),
                                ),
                            ),
                        )
                        continue
                    instances = tracker.track(snapshot.rgb)
                    require_surface = (
                        text_recovery_active
                        or table_required is None
                        or bool(table_required())
                    )
                    previous_target_id = target_id
                    previous_surface_id = surface_id
                    if text_recovery_active:
                        target = _best_tracked_instance(instances, 0)
                        surface = _best_tracked_instance(instances, 1)
                        target_reacquired = False
                        surface_reacquired = False
                        target_mismatch = False
                        surface_mismatch = False
                    else:
                        target, target_reacquired, target_mismatch = _resolve_target(
                            instances, target_id
                        )
                        surface, surface_reacquired, surface_mismatch = _resolve_target(
                            instances, surface_id, class_index=1
                        )
                    surface_detection_missing = require_surface and (
                        surface is None or surface_mismatch
                    )
                    detection_missing = (
                        target is None or surface_detection_missing
                    )
                    if detection_missing or target_mismatch:
                        if target_mismatch:
                            error = "target track ID/class mismatch"
                        elif target is None:
                            error = (
                                "missing text-recovery target"
                                if text_recovery_active
                                else "missing tracked target"
                            )
                        elif text_recovery_active:
                            error = "missing text-recovery desk"
                        elif surface_mismatch:
                            error = "desk track ID/class mismatch"
                        else:
                            error = "missing tracked desk"
                        event_kind = "invalid"
                        hard_failure = target_mismatch
                        event_details: dict[str, Any] = {
                            "target_id_mismatch": target_mismatch,
                            "surface_id_mismatch": surface_mismatch,
                            "surface_required": require_surface,
                            "recovery_mode": (
                                "target_text_surface_text"
                                if text_recovery_active
                                else "visual"
                            ),
                        }
                        if text_recovery_active and not hard_failure:
                            text_recovery_missing_frames += 1
                            event_details["text_recovery_missing_frames"] = (
                                text_recovery_missing_frames
                            )
                            if (
                                text_recovery_missing_frames
                                >= SINGLE_CAMERA_TEXT_RECOVERY_FRAMES
                            ):
                                event_kind = "error"
                                hard_failure = True
                                error = (
                                    "single-camera two-text recovery exhausted "
                                    f"after {SINGLE_CAMERA_TEXT_RECOVERY_FRAMES} "
                                    f"frames: {error}"
                                )
                        elif not hard_failure:
                            visual_missing_frames += 1
                            event_details["visual_missing_frames"] = (
                                visual_missing_frames
                            )
                            if (
                                visual_missing_frames
                                >= SINGLE_CAMERA_TEXT_RECOVERY_FRAMES
                            ):
                                begin_text_recovery(frame_index)
                                event_kind = "recovering"
                                event_details.update(
                                    {
                                        "recovery_mode": (
                                            "target_text_surface_text"
                                        ),
                                        "target_prompt": (
                                            SINGLE_CAMERA_TEXT_TARGET_PROMPT
                                        ),
                                        "surface_prompt": (
                                            SINGLE_CAMERA_TEXT_SURFACE_PROMPT
                                        ),
                                    }
                                )
                        _publish_worker_event(
                            events, observation_events, diagnostics,
                            RawServoEvent(
                                generation,
                                event_kind,
                                output_dir=str(output_dir),
                                error=error,
                                hard=hard_failure,
                                details=event_details,
                                frame=_diagnostic_frame(
                                    frame_index,
                                    snapshot,
                                    target,
                                    None if surface_mismatch else surface,
                                    None,
                                    kind=event_kind,
                                    error=error,
                                ),
                            ),
                        )
                        if event_kind == "error":
                            gate.cancel(generation)
                        continue
                    if surface_mismatch:
                        surface = None
                    try:
                        observation = _observation(snapshot, target, surface, calibration)
                        if require_surface and observation.table is None:
                            raise ValueError(
                                observation.table_geometry_error
                                or (
                                    "missing text-recovery desk geometry"
                                    if text_recovery_active
                                    else "missing tracked desk geometry"
                                )
                            )
                    except (ValueError, BasePoseCameraError) as exc:
                        event_kind = "invalid"
                        hard_failure = False
                        event_details: dict[str, Any] = {}
                        if text_recovery_active:
                            text_recovery_missing_frames += 1
                            event_details = {
                                "recovery_mode": "target_text_surface_text",
                                "text_recovery_missing_frames": (
                                    text_recovery_missing_frames
                                ),
                            }
                            if (
                                text_recovery_missing_frames
                                >= SINGLE_CAMERA_TEXT_RECOVERY_FRAMES
                            ):
                                event_kind = "error"
                                hard_failure = True
                        else:
                            visual_missing_frames += 1
                            event_details = {
                                "recovery_mode": "visual",
                                "surface_required": require_surface,
                                "visual_missing_frames": visual_missing_frames,
                            }
                            if (
                                visual_missing_frames
                                >= SINGLE_CAMERA_TEXT_RECOVERY_FRAMES
                            ):
                                begin_text_recovery(frame_index)
                                event_kind = "recovering"
                                event_details.update(
                                    {
                                        "recovery_mode": (
                                            "target_text_surface_text"
                                        ),
                                        "target_prompt": (
                                            SINGLE_CAMERA_TEXT_TARGET_PROMPT
                                        ),
                                        "surface_prompt": (
                                            SINGLE_CAMERA_TEXT_SURFACE_PROMPT
                                        ),
                                    }
                                )
                        error = (
                            "single-camera two-text recovery exhausted "
                            f"after {SINGLE_CAMERA_TEXT_RECOVERY_FRAMES} "
                            f"frames: {exc}"
                            if event_kind == "error"
                            else str(exc)
                        )
                        _publish_worker_event(
                            events, observation_events, diagnostics,
                            RawServoEvent(
                                generation,
                                event_kind,
                                output_dir=str(output_dir),
                                error=error,
                                hard=hard_failure,
                                details=event_details,
                                frame=_diagnostic_frame(
                                    frame_index,
                                    snapshot,
                                    target,
                                    surface,
                                    None,
                                    kind=event_kind,
                                    error=error,
                                ),
                            ),
                        )
                        if event_kind == "error":
                            gate.cancel(generation)
                        continue
                    recovered_from_text = False
                    visual_missing_frames = 0
                    if text_recovery_active:
                        height, width = snapshot.rgb.shape[:2]
                        visual_artifact = tracker.start(
                            snapshot.rgb,
                            target_prompt=spec.target_prompt,
                            target_bbox=pixel_bbox_to_normalized(
                                target.bbox_xyxy, width, height
                            ),
                            surface_prompt=SINGLE_CAMERA_TEXT_SURFACE_PROMPT,
                            surface_bboxes=(
                                pixel_bbox_to_normalized(
                                    surface.bbox_xyxy, width, height
                                ),
                            ),
                        )
                        _write_json(
                            output_dir
                            / (
                                "yoloe_text_recovery_visual_prompt_"
                                f"{frame_index:06d}.json"
                            ),
                            visual_artifact,
                        )
                        text_recovery_active = False
                        text_recovery_missing_frames = 0
                        target_id = target.track_id
                        surface_id = surface.track_id
                        recovered_from_text = True
                        reference_update_gate = (
                            TargetReferenceUpdateGate(
                                interval_frames=(
                                    config.raw_reference_update_interval_frames
                                ),
                                min_confidence=(
                                    config.raw_reference_update_min_confidence
                                ),
                            )
                            if reference_updater is not None
                            else None
                        )
                    if target_reacquired:
                        target_id = target.track_id
                    if surface_reacquired:
                        surface_id = surface.track_id
                    event_details: dict[str, Any] = {
                        "surface_id_mismatch": surface_mismatch
                    }
                    if recovered_from_text:
                        event_details.update(
                            {
                                "text_recovery_succeeded": True,
                                "text_target_prompt": (
                                    SINGLE_CAMERA_TEXT_TARGET_PROMPT
                                ),
                                "text_surface_prompt": (
                                    SINGLE_CAMERA_TEXT_SURFACE_PROMPT
                                ),
                                "visual_reference_source_frame": frame_index,
                            }
                        )
                    if target_reacquired:
                        event_details.update(
                            {
                                "target_reacquired": True,
                                "previous_target_id": previous_target_id,
                                "target_track_id": target_id,
                            }
                        )
                    if surface_reacquired:
                        event_details.update(
                            {
                                "surface_reacquired": True,
                                "previous_surface_id": previous_surface_id,
                                "surface_track_id": surface_id,
                            }
                        )
                    should_submit_reference = False
                    reference_trigger = "disabled"
                    if (
                        reference_update_gate is not None
                        and not recovered_from_text
                    ):
                        should_submit_reference, reference_trigger = (
                            reference_update_gate.consider(
                                frame_index,
                                confidence=target.confidence,
                            )
                        )
                    if (
                        reference_updater is not None
                        and not recovered_from_text
                        and target.confidence
                        >= config.raw_reference_update_min_confidence
                    ):
                        update_result = reference_updater.poll_latest()
                        if update_result is not None:
                            if update_result.generation != generation:
                                event_details["target_reference_update_discarded"] = {
                                    "source_generation": update_result.generation,
                                    "source_frame": update_result.frame_index,
                                }
                            elif frame_index - update_result.frame_index > max(
                                5,
                                2 * config.raw_reference_update_interval_frames,
                            ):
                                event_details["target_reference_update_discarded"] = {
                                    "reason": "stale",
                                    "source_frame": update_result.frame_index,
                                    "age_frames": (
                                        frame_index - update_result.frame_index
                                    ),
                                }
                            elif update_result.accepted:
                                try:
                                    tracker.install_target_embedding(
                                        update_result.embedding
                                    )
                                except Exception as exc:
                                    event_details[
                                        "target_reference_update_error"
                                    ] = str(exc)
                                else:
                                    event_details["target_reference_update_applied"] = {
                                        "source_frame": update_result.frame_index,
                                        "confidence": update_result.confidence,
                                        "iou": update_result.iou,
                                    }
                            else:
                                event_details["target_reference_update_rejected"] = {
                                    "source_frame": update_result.frame_index,
                                    "reason": update_result.reason,
                                    "confidence": update_result.confidence,
                                    "iou": update_result.iou,
                                }
                    elif reference_trigger == "low_confidence":
                        event_details["target_reference_update_paused"] = (
                            reference_trigger
                        )
                    if (
                        reference_updater is not None
                        and not recovered_from_text
                        and should_submit_reference
                    ):
                        reference_request = TargetReferenceRequest(
                            generation=generation,
                            frame_index=frame_index,
                            rgb=snapshot.rgb,
                            target_prompt=spec.target_prompt,
                            target_bbox_xyxy=target.bbox_xyxy,
                        )
                        reference_updater.submit(reference_request)
                        event_details["target_reference_update_scheduled"] = {
                            "source_frame": frame_index,
                            "trigger": reference_trigger,
                        }
                    _publish_worker_event(
                        events, observation_events, diagnostics,
                        RawServoEvent(
                            generation,
                            "observation",
                            observation=observation,
                            output_dir=str(output_dir),
                            details=event_details,
                            frame=_diagnostic_frame(
                                frame_index,
                                snapshot,
                                target,
                                surface,
                                observation,
                                kind="observation",
                            ),
                        ),
                    )
            except Exception as exc:
                _publish_worker_event(
                    events, observation_events, diagnostics,
                    RawServoEvent(
                        generation,
                        "error",
                        output_dir=None if output_dir is None else str(output_dir),
                        error=str(exc),
                        hard=True,
                    ),
                )
                gate.cancel(generation)
    finally:
        if reference_updater is not None:
            reference_updater.close()
        if camera is not None:
            camera.close()


class RawServoRuntime:
    """Operator gating, watchdog, diagnostics, and direct velocity publication."""

    def __init__(
        self,
        config: Any,
        *,
        publish: Callable[[str], None],
        requests: queue.Queue[int | None] | None = None,
        events: queue.Queue[RawServoEvent] | None = None,
        gate: GenerationGate | None = None,
        stop_event: threading.Event | None = None,
        logger: Callable[[str], None] = print,
        monotonic: Callable[[], float] = time.monotonic,
        diagnostics: AsyncFrameDiagnosticsWriter | None = None,
        orientation_provider: (
            Callable[[float], Mapping[str, Any] | None] | None
        ) = None,
        navigation_started: Callable[[], None] | None = None,
        navigation_finished: Callable[[], None] | None = None,
    ):
        self.config = config
        self.publish = publish
        self.requests = requests or queue.Queue(maxsize=1)
        self.events = events or queue.Queue()
        self.observation_events: queue.Queue[RawServoEvent] = queue.Queue(maxsize=1)
        self.gate = gate or GenerationGate()
        self.stop_event = stop_event or threading.Event()
        self.logger = logger
        self.monotonic = monotonic
        self.controller = VisualServoController(
            target_distance_m=config.raw_head_target_distance_m,
            forward_tolerance_m=config.raw_forward_tolerance_m,
            lateral_tolerance_m=config.raw_lateral_tolerance_m,
            command_ttl_s=config.raw_command_ttl_s,
            max_run_s=config.raw_max_run_s,
            min_linear_speed_m_s=config.raw_min_linear_speed_m_s,
            max_lateral_speed_m_s=config.raw_max_lateral_speed_m_s,
            min_yaw_speed_rad_s=config.raw_min_yaw_speed_rad_s,
            yaw_tolerance_deg=config.raw_yaw_tolerance_deg,
            yaw_coarse_speed_rad_s=config.raw_yaw_coarse_speed_rad_s,
            yaw_trim_speed_rad_s=config.raw_yaw_trim_speed_rad_s,
            forward_recenter_yaw_speed_rad_s=(
                config.raw_forward_recenter_yaw_speed_rad_s
            ),
            post_stop_sample_s=config.raw_post_stop_sample_s,
            allow_missing_table=bool(
                getattr(config, "raw_allow_missing_table", 0)
            ),
            horizontal_guard_fraction=config.raw_horizontal_guard_fraction,
            horizontal_recovery_fraction=config.raw_horizontal_recovery_fraction,
        )
        self.generation = 0
        self.phase = "idle"
        self.output_dir: str | None = None
        self._diagnostics = diagnostics
        self.orientation_provider = orientation_provider
        self.navigation_started = navigation_started
        self.navigation_finished = navigation_finished
        self._navigation_auxiliary_active = False
        self.last_observation_at: float | None = None
        self.last_event_produced_at: float | None = None
        self.last_event_received_at: float | None = None
        self.last_applied_frame_index: int | None = None
        self.current_attempt_id = 0
        self.active_camera_stream: str | None = None
        self.vertical_recenter_armed = False
        self.viewer_target_bbox_xyxy: (
            tuple[float, float, float, float] | None
        ) = None
        self.viewer_target_lateral_anchor_px: tuple[float, float] | None = None
        self.viewer_table_edge_endpoints_px: (
            tuple[tuple[float, float], tuple[float, float]] | None
        ) = None
        self.viewer_desk_mask_row_spans: (
            tuple[tuple[int, int, int], ...] | None
        ) = None
        self.viewer_image_size: tuple[int, int] | None = None
        self.navigation_started_at: float | None = None
        self.soft_stale = False
        self.next_publish_at: float | None = None
        self._shutdown = False

    def _zero(self) -> ServoCommand:
        return ServoCommand(0.0, 0.0, 0.0, self.config.raw_command_ttl_s)

    @staticmethod
    def _event_camera_stream(details: Mapping[str, Any]) -> str | None:
        value = details.get("live_stream") or details.get("camera_stream")
        if value is None:
            return None
        stream = str(value).strip()
        return stream or None

    def _is_vertical_recenter_switch(
        self,
        *,
        previous_stream: str | None,
        next_stream: str | None,
        details: Mapping[str, Any],
    ) -> bool:
        if self.config.mode != "dual_raw_yoloe_servo":
            return False
        chest_stream = str(
            getattr(self.config, "dual_chest_camera_stream", "chest_view")
        )
        head_stream = str(
            getattr(self.config, "dual_head_camera_stream", "ego_view")
        )
        stage = str(details.get("failover_stage") or "")
        return (
            previous_stream == chest_stream
            and next_stream == head_stream
            and stage in {"head_monitor", "head_monitor_qwen"}
        )

    def _reset_controller(self, now: float) -> None:
        chest_stream = str(
            getattr(self.config, "dual_chest_camera_stream", "chest_view")
        )
        active_stream = self.active_camera_stream
        if (
            active_stream is None
            and self.config.mode != "dual_raw_yoloe_servo"
        ):
            active_stream = str(getattr(self.config, "camera_stream", "ego_view"))
        chest_camera_active = active_stream == chest_stream
        self.controller.target_distance_m = float(
            self.config.raw_chest_target_distance_m
            if chest_camera_active
            else self.config.raw_head_target_distance_m
        )
        self.controller.reset(
            now,
            initial_phase=(
                ServoPhase.FORWARD_APPROACH
                if chest_camera_active
                else ServoPhase.VERTICAL_RECENTER
                if self.vertical_recenter_armed
                else ServoPhase.YAW_ALIGN
            ),
        )

    def _clear_viewer_overlay(self) -> None:
        self.viewer_target_bbox_xyxy = None
        self.viewer_target_lateral_anchor_px = None
        self.viewer_table_edge_endpoints_px = None
        self.viewer_desk_mask_row_spans = None
        self.viewer_image_size = None

    def _set_viewer_overlay(self, observation: RawServoObservation) -> None:
        self.viewer_target_bbox_xyxy = tuple(
            float(value) for value in observation.target_bbox_xyxy
        )
        self.viewer_target_lateral_anchor_px = (
            None
            if observation.target.lateral_anchor_px is None
            else tuple(
                float(value) for value in observation.target.lateral_anchor_px
            )
        )
        self.viewer_table_edge_endpoints_px = (
            None
            if observation.table is None
            or observation.table.line_endpoints_px is None
            else tuple(
                tuple(float(value) for value in point)
                for point in observation.table.line_endpoints_px
            )
        )
        if observation.desk_mask is None:
            self.viewer_desk_mask_row_spans = None
        else:
            expected_shape = (
                int(observation.image_height),
                int(observation.image_width),
            )
            if observation.desk_mask.shape != expected_shape:
                raise ValueError(
                    "desk mask shape does not match viewer image size"
                )
            self.viewer_desk_mask_row_spans = _binary_mask_row_spans(
                observation.desk_mask
            )
        self.viewer_image_size = (
            int(observation.image_width),
            int(observation.image_height),
        )

    def _publish(self, command: ServoCommand, action: str) -> None:
        active_camera_stream = self.active_camera_stream
        if (
            active_camera_stream is None
            and self.config.mode != "dual_raw_yoloe_servo"
        ):
            active_camera_stream = str(self.config.camera_stream)
        self.publish(
            build_servo_velocity_message(
                command,
                action=action,
                camera_stream=active_camera_stream,
                viewer_target_bbox_xyxy=self.viewer_target_bbox_xyxy,
                viewer_target_lateral_anchor_px=(
                    self.viewer_target_lateral_anchor_px
                ),
                viewer_table_edge_endpoints_px=(
                    self.viewer_table_edge_endpoints_px
                ),
                viewer_desk_mask_row_spans=(
                    self.viewer_desk_mask_row_spans
                ),
                viewer_image_size=self.viewer_image_size,
            )
        )

    def _stop_sequence(self) -> None:
        for _ in range(self.config.final_stop_count):
            self._publish(self._zero(), "stop")

    def _record(self, event: str, **fields: Any) -> None:
        directory = Path(self.output_dir or self.config.output_root).resolve()
        line = json.dumps(
            {
                "timestamp_unix_s": time.time(),
                "event": event,
                "generation": self.generation,
                **fields,
            },
            ensure_ascii=False,
        )
        try:
            directory.mkdir(parents=True, exist_ok=True)
            with (directory / "raw_servo_events.jsonl").open(
                "a", encoding="utf-8"
            ) as handle:
                handle.write(line + "\n")
        except OSError as exc:
            self.logger(f"[RawServo] diagnostic write failed: {exc}")
        else:
            self.logger(line)

    def _start_navigation_auxiliary(self) -> None:
        if self._navigation_auxiliary_active or self.navigation_started is None:
            return
        try:
            self.navigation_started()
        except Exception as exc:
            self.logger(f"[RawServo] WARNING navigation viewer failed: {exc}")
            return
        self._navigation_auxiliary_active = True

    def _stop_navigation_auxiliary(self) -> None:
        if not self._navigation_auxiliary_active:
            return
        self._navigation_auxiliary_active = False
        if self.navigation_finished is None:
            return
        try:
            self.navigation_finished()
        except Exception as exc:
            self.logger(f"[RawServo] WARNING navigation viewer stop failed: {exc}")

