def _finite(value: Any, field: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise BasePoseValidationError(f"{field} must be numeric")
    result = float(value)
    if not math.isfinite(result):
        raise BasePoseValidationError(f"{field} must be finite")
    return result


def _validate_bbox(value: Any, field: str) -> tuple[float, float, float, float]:
    if not isinstance(value, list) or len(value) != 4:
        raise BasePoseValidationError(f"{field} must contain four coordinates")
    bbox = tuple(_finite(item, field) for item in value)
    if not all(0.0 <= item <= 1000.0 for item in bbox):
        raise BasePoseValidationError(f"{field} must be normalized to [0,1000]")
    if bbox[0] >= bbox[2] or bbox[1] >= bbox[3]:
        raise BasePoseValidationError(f"{field} corner order is invalid")
    return bbox  # type: ignore[return-value]


def validate_raw_servo_target(value: Any) -> RawServoTargetSpec:
    if not isinstance(value, Mapping) or set(value) != TARGET_OUTPUT_KEYS:
        raise BasePoseValidationError("raw servo target has an invalid object schema")
    status = value["status"]
    if status not in {"READY", "UNSURE", "UNSAFE"}:
        raise BasePoseValidationError("raw servo target status is invalid")

    def parse_object(name: str) -> tuple[str, tuple[float, float, float, float]]:
        item = value[name]
        if not isinstance(item, Mapping) or set(item) != TARGET_KEYS:
            raise BasePoseValidationError(f"{name} has an invalid object schema")
        prompt = item["text_prompt"]
        if not isinstance(prompt, str) or not prompt.strip():
            raise BasePoseValidationError(f"{name}.text_prompt must be non-empty")
        normalized_prompt = re.sub(
            r"\btables?\b",
            lambda match: "desks" if match.group(0).lower().endswith("s") else "desk",
            prompt.strip(),
            flags=re.IGNORECASE,
        )
        return normalized_prompt, _validate_bbox(
            item["bbox_2d"], f"{name}.bbox_2d"
        )

    target_prompt, target_bbox = parse_object("primary_target")
    strings: dict[str, str] = {}
    for key in ("manipulation_anchor", "selection_reason", "limitations"):
        item = value[key]
        if not isinstance(item, str):
            raise BasePoseValidationError(f"{key} must be a string")
        strings[key] = item
    confidence = _finite(value["confidence"], "confidence")
    if not 0.0 <= confidence <= 1.0:
        raise BasePoseValidationError("confidence must be in [0,1]")
    if status != "READY":
        raise BasePoseValidationError(f"target initialization returned {status}")
    return RawServoTargetSpec(
        status=status,
        target_prompt=target_prompt,
        target_bbox=target_bbox,
        manipulation_anchor=strings["manipulation_anchor"],
        selection_reason=strings["selection_reason"],
        confidence=confidence,
        limitations=strings["limitations"],
    )


