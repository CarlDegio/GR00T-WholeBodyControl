def ground_raw_servo_references(
    config: Any,
    rgb_path: str | Path,
    output_dir: str | Path,
    *,
    client_factory: Callable[[], Any] | None = None,
) -> tuple[
    RawServoTargetSpec,
    tuple[tuple[float, float, float, float], ...],
]:
    image_path = Path(rgb_path).resolve()
    workdir = Path(output_dir).resolve()
    target_prompt = build_raw_servo_target_prompt(
        config.task, calibration_from_config(config)
    )
    table_prompt = build_raw_servo_table_prompt()
    _write_text(workdir / "target_prompt.txt", target_prompt)
    _write_text(workdir / "table_prompt.txt", table_prompt)

    def make_client() -> Any:
        if client_factory is not None:
            return client_factory()
        return _client_from_config(config)

    def run_target() -> RawServoTargetSpec:
        raw_target = make_client().run(
            prompt=target_prompt,
            image_paths=[image_path],
            schema=RAW_SERVO_TARGET_SCHEMA,
            schema_filename="target_schema.json",
            cwd=workdir,
        )
        _write_json(workdir / "target_result.json", raw_target)
        return validate_raw_servo_target(raw_target)

    def run_table() -> tuple[tuple[float, float, float, float], ...]:
        raw_table = make_client().run(
            prompt=table_prompt,
            image_paths=[image_path],
            schema=GROUNDING_SCHEMA,
            schema_filename="table_schema.json",
            cwd=workdir,
        )
        _write_json(workdir / "table_result.json", raw_table)
        return validate_raw_servo_table(raw_table)

    with ThreadPoolExecutor(
        max_workers=2, thread_name_prefix="raw-servo-grounding"
    ) as pool:
        target_future = pool.submit(run_target)
        table_future = pool.submit(run_table)
        return target_future.result(), table_future.result()


def _resolve_target(
    instances: list[TrackedInstance],
    expected_id: int,
    class_index: int = 0,
) -> tuple[TrackedInstance | None, bool, bool]:
    candidates = [item for item in instances if item.class_index == class_index]
    for item in candidates:
        if item.track_id == expected_id:
            return item, False, False
    if candidates:
        return max(candidates, key=lambda item: item.confidence), True, False
    wrong_class = any(item.track_id == expected_id for item in instances)
    return None, False, wrong_class


def _observation(
    snapshot: AlignedRGBDSnapshot,
    target: TrackedInstance,
    surface: TrackedInstance | None,
    calibration: RawServoCalibration,
) -> RawServoObservation:
    table = None
    table_error = None
    if surface is not None:
        try:
            table = estimate_table_geometry(snapshot, surface.mask, calibration)
        except ValueError as exc:
            table = None
            table_error = str(exc)
    return RawServoObservation(
        target=estimate_target_geometry(
            snapshot,
            target.mask,
            calibration,
            bbox_xyxy=target.bbox_xyxy,
        ),
        table=table,
        camera_timestamp=snapshot.timestamp,
        target_track_id=target.track_id,
        surface_track_id=None if surface is None else surface.track_id,
        target_bbox_xyxy=target.bbox_xyxy,
        image_width=int(snapshot.rgb.shape[1]),
        image_height=int(snapshot.rgb.shape[0]),
        table_geometry_error=table_error,
    )



def _diagnostic_frame(
    frame_index: int,
    snapshot: AlignedRGBDSnapshot,
    target: TrackedInstance | None,
    surface: TrackedInstance | None,
    observation: RawServoObservation | None,
    *,
    kind: str,
    error: str | None = None,
) -> DetectionFrameData:
    target_geometry = None
    table_geometry = None
    if observation is not None:
        target_geometry = {
            "forward_m": observation.target.forward_m,
            "right_m": observation.target.right_m,
            "body_xyz_m": list(observation.target.body_xyz_m),
            "valid_depth_pixels": observation.target.valid_depth_pixels,
            "valid_ratio": observation.target.valid_ratio,
            "median_depth_m": observation.target.median_depth_m,
        }
        if observation.table is not None:
            table_geometry = {
                "yaw_error_rad": observation.table.yaw_error_rad,
                "line_length_m": observation.table.line_length_m,
                "inlier_count": observation.table.inlier_count,
                "residual_m": observation.table.residual_m,
                "line_center_xy_m": list(observation.table.line_center_xy_m),
            }
    return DetectionFrameData(
        frame_index=frame_index,
        camera_timestamp=snapshot.timestamp,
        rgb=snapshot.rgb.copy(),
        target_bbox_xyxy=None if target is None else target.bbox_xyxy,
        target_mask=None if target is None else target.mask.copy(),
        target_track_id=None if target is None else target.track_id,
        target_confidence=None if target is None else target.confidence,
        surface_bbox_xyxy=None if surface is None else surface.bbox_xyxy,
        surface_mask=None if surface is None else surface.mask.copy(),
        surface_track_id=None if surface is None else surface.track_id,
        surface_confidence=None if surface is None else surface.confidence,
        target_geometry=target_geometry,
        table_geometry=table_geometry,
        table_geometry_error=(
            None if observation is None else observation.table_geometry_error
        ),
        perception_kind=kind,
        perception_error=error,
    )


def run_raw_servo_worker(
    config: Any,
    requests: queue.Queue[int | None],
    events: queue.Queue[RawServoEvent],
    gate: GenerationGate,
    stop_event: threading.Event,
    *,
    observation_events: queue.Queue[RawServoEvent] | None = None,
    diagnostics: AsyncFrameDiagnosticsWriter | None = None,
    camera_factory: Callable[[], AlignedRGBDCamera] | None = None,
    client_factory: Callable[[], Any] | None = None,
    tracker_factory: Callable[[], Any] | None = None,
    reference_updater_factory: Callable[[], Any] | None = None,
) -> None:
    calibration = calibration_from_config(config)
    camera: AlignedRGBDCamera | None = None
    tracker: Any | None = None
    reference_updater: Any | None = None
    try:
        while not stop_event.is_set():
            try:
                generation = requests.get(timeout=0.1)
            except queue.Empty:
                continue
            if generation is None or stop_event.is_set():
                return
            output_dir: Path | None = None
            try:
                if camera is None:
                    camera = (
                        camera_factory()
                        if camera_factory is not None
                        else AlignedRGBDCamera(
                            config.camera_host,
                            config.camera_port,
                            stream_name=config.camera_stream,
                            require_depth=True,
                            required_depth_source=None,
                            timeout_ms=config.camera_timeout_ms,
                        )
                    )
                snapshot = camera.capture()
                calibration.validate_snapshot(snapshot)
                stamp = time.strftime("%Y%m%d_%H%M%S")
                output_dir = (
                    Path(config.output_root).resolve()
                    / f"raw_yoloe_{stamp}_g{generation}"
                )
                output_dir.mkdir(parents=True, exist_ok=False)
                rgb_path = output_dir / "initial_rgb.png"
                _save_png(rgb_path, snapshot.rgb, rgb=True)
                assert snapshot.depth_raw is not None
                _save_png(output_dir / "initial_depth_raw.png", snapshot.depth_raw)
                spec, table_bboxes = ground_raw_servo_references(
                    config,
                    rgb_path,
                    output_dir,
                    client_factory=client_factory,
                )
                if not gate.is_active(generation):
                    continue
                if reference_updater is None:
                    if reference_updater_factory is not None:
                        reference_updater = reference_updater_factory()
                    elif (
                        getattr(config, "raw_reference_update_interval_frames", 5) > 0
                        and tracker_factory is None
                    ):
                        reference_updater = AsyncTargetReferenceUpdater(
                            lambda: YoloeTargetReferenceEncoder(
                                config.raw_yoloe_model_path,
                                confidence=config.raw_yoloe_confidence,
                                imgsz=config.raw_yoloe_imgsz,
                                device=config.raw_yoloe_device,
                            ),
                            min_confidence=config.raw_reference_update_min_confidence,
                            min_iou=config.raw_reference_update_min_iou,
                        )
                if tracker is None:
                    tracker = (
                        tracker_factory()
                        if tracker_factory
                        else YoloePersistentTracker(
                            config.raw_yoloe_model_path,
                            confidence=config.raw_yoloe_confidence,
                            imgsz=config.raw_yoloe_imgsz,
                            device=config.raw_yoloe_device,
                        )
                    )
                reference_update_gate = (
                    TargetReferenceUpdateGate(
                        interval_frames=config.raw_reference_update_interval_frames,
                        min_confidence=config.raw_reference_update_min_confidence,
                        freeze_y2_px=config.raw_reference_update_freeze_y2_px,
                        resume_y2_px=config.raw_reference_update_resume_y2_px,
                    )
                    if reference_updater is not None
                    else None
                )
                visual_prompt = tracker.start(
                    snapshot.rgb,
                    target_prompt=spec.target_prompt,
                    target_bbox=spec.target_bbox,
                    surface_prompt="table",
                    surface_bboxes=table_bboxes,
                )
                _write_json(output_dir / "yoloe_reference_prompt.json", visual_prompt)
                instances = tracker.track(snapshot.rgb)
                target = select_initial_instance(
                    instances,
                    class_index=0,
                    grounded_bboxes=(spec.target_bbox,),
                    width=calibration.width,
                    height=calibration.height,
                )
                surface = select_initial_instance(
                    instances,
                    class_index=1,
                    grounded_bboxes=table_bboxes,
                    width=calibration.width,
                    height=calibration.height,
                )
                observation = _observation(snapshot, target, surface, calibration)
                frame_index = 0
                _write_json(
                    output_dir / "tracking_ids.json",
                    {
                        "target_track_id": target.track_id,
                        "surface_track_id": surface.track_id,
                        "target_prompt": spec.target_prompt,
                        "surface_prompt": "table",
                        "table_bboxes": [list(bbox) for bbox in table_bboxes],
                        "reference_boxes_xyxy": visual_prompt[
                            "reference_boxes_xyxy"
                        ],
                    },
                )
                _publish_worker_event(
                    events, observation_events, diagnostics,
                    RawServoEvent(
                        generation,
                        "initialized",
                        observation=observation,
                        output_dir=str(output_dir),
                        details={
                            "target_prompt": spec.target_prompt,
                            "surface_prompt": "table",
                            "table_bboxes": [list(bbox) for bbox in table_bboxes],
                            "reference_boxes_xyxy": visual_prompt[
                                "reference_boxes_xyxy"
                            ],
                            "target_track_id": target.track_id,
                            "surface_track_id": surface.track_id,
                        },
                        frame=_diagnostic_frame(
                            frame_index,
                            snapshot,
                            target,
                            surface,
                            observation,
                            kind="initialized",
                        ),
                    ),
                )
                target_id, surface_id = target.track_id, surface.track_id
                next_frame = time.monotonic()
                while gate.is_active(generation) and not stop_event.is_set():
                    delay = next_frame - time.monotonic()
                    if delay > 0.0:
                        stop_event.wait(min(delay, 0.05))
                        continue
                    next_frame = time.monotonic() + 1.0 / config.raw_servo_hz
                    snapshot = camera.capture()
                    frame_index += 1
                    try:
                        calibration.validate_snapshot(snapshot)
                    except BasePoseCameraError as exc:
                        _publish_worker_event(
                            events, observation_events, diagnostics,
                            RawServoEvent(
                                generation,
                                "invalid",
                                output_dir=str(output_dir),
                                error=str(exc),
                                hard=True,
                                frame=_diagnostic_frame(
                                    frame_index,
                                    snapshot,
                                    None,
                                    None,
                                    None,
                                    kind="invalid",
                                    error=str(exc),
                                ),
                            ),
                        )
                        continue
                    instances = tracker.track(snapshot.rgb)
                    previous_target_id = target_id
                    previous_surface_id = surface_id
                    target, target_reacquired, target_mismatch = _resolve_target(
                        instances, target_id
                    )
                    surface, surface_reacquired, surface_mismatch = _resolve_target(
                        instances, surface_id, class_index=1
                    )
                    if target is None or target_mismatch:
                        error = (
                            "target track ID/class mismatch"
                            if target_mismatch
                            else "missing tracked target"
                        )
                        _publish_worker_event(
                            events, observation_events, diagnostics,
                            RawServoEvent(
                                generation,
                                "invalid",
                                output_dir=str(output_dir),
                                error=error,
                                hard=target_mismatch,
                                details={"target_id_mismatch": target_mismatch},
                                frame=_diagnostic_frame(
                                    frame_index,
                                    snapshot,
                                    target,
                                    None if surface_mismatch else surface,
                                    None,
                                    kind="invalid",
                                    error=error,
                                ),
                            ),
                        )
                        continue
                    if surface_mismatch:
                        surface = None
                    try:
                        observation = _observation(snapshot, target, surface, calibration)
                    except (ValueError, BasePoseCameraError) as exc:
                        _publish_worker_event(
                            events, observation_events, diagnostics,
                            RawServoEvent(
                                generation,
                                "invalid",
                                output_dir=str(output_dir),
                                error=str(exc),
                                hard=False,
                                frame=_diagnostic_frame(
                                    frame_index,
                                    snapshot,
                                    target,
                                    surface,
                                    None,
                                    kind="invalid",
                                    error=str(exc),
                                ),
                            ),
                        )
                        continue
                    if target_reacquired:
                        target_id = target.track_id
                    if surface_reacquired:
                        surface_id = surface.track_id
                    event_details: dict[str, Any] = {
                        "surface_id_mismatch": surface_mismatch
                    }
                    if target_reacquired:
                        event_details.update(
                            {
                                "target_reacquired": True,
                                "previous_target_id": previous_target_id,
                                "target_track_id": target_id,
                            }
                        )
                    if surface_reacquired:
                        event_details.update(
                            {
                                "surface_reacquired": True,
                                "previous_surface_id": previous_surface_id,
                                "surface_track_id": surface_id,
                            }
                        )
                    should_submit_reference = False
                    reference_trigger = "disabled"
                    if reference_update_gate is not None:
                        should_submit_reference, reference_trigger = (
                            reference_update_gate.consider(
                                frame_index,
                                confidence=target.confidence,
                                bbox_xyxy=target.bbox_xyxy,
                            )
                        )
                    if (
                        reference_updater is not None
                        and target.bbox_xyxy[3]
                        >= config.raw_reference_update_resume_y2_px
                        and target.confidence
                        >= config.raw_reference_update_min_confidence
                    ):
                        update_result = reference_updater.poll_latest()
                        if update_result is not None:
                            if update_result.generation != generation:
                                event_details["target_reference_update_discarded"] = {
                                    "source_generation": update_result.generation,
                                    "source_frame": update_result.frame_index,
                                }
                            elif frame_index - update_result.frame_index > max(
                                5,
                                2 * config.raw_reference_update_interval_frames,
                            ):
                                event_details["target_reference_update_discarded"] = {
                                    "reason": "stale",
                                    "source_frame": update_result.frame_index,
                                    "age_frames": (
                                        frame_index - update_result.frame_index
                                    ),
                                }
                            elif update_result.accepted:
                                try:
                                    tracker.install_target_embedding(
                                        update_result.embedding
                                    )
                                except Exception as exc:
                                    event_details[
                                        "target_reference_update_error"
                                    ] = str(exc)
                                else:
                                    event_details["target_reference_update_applied"] = {
                                        "source_frame": update_result.frame_index,
                                        "confidence": update_result.confidence,
                                        "iou": update_result.iou,
                                    }
                            else:
                                event_details["target_reference_update_rejected"] = {
                                    "source_frame": update_result.frame_index,
                                    "reason": update_result.reason,
                                    "confidence": update_result.confidence,
                                    "iou": update_result.iou,
                                }
                    elif reference_trigger in {
                        "vertical_danger",
                        "vertical_recovery_pending",
                        "reference_near_top",
                        "low_confidence",
                    }:
                        event_details["target_reference_update_paused"] = (
                            reference_trigger
                        )
                    if (
                        reference_updater is not None
                        and should_submit_reference
                    ):
                        reference_request = TargetReferenceRequest(
                            generation=generation,
                            frame_index=frame_index,
                            rgb=snapshot.rgb,
                            target_prompt=spec.target_prompt,
                            target_bbox_xyxy=target.bbox_xyxy,
                        )
                        reference_updater.submit(reference_request)
                        event_details["target_reference_update_scheduled"] = {
                            "source_frame": frame_index,
                            "trigger": reference_trigger,
                        }
                    _publish_worker_event(
                        events, observation_events, diagnostics,
                        RawServoEvent(
                            generation,
                            "observation",
                            observation=observation,
                            output_dir=str(output_dir),
                            details=event_details,
                            frame=_diagnostic_frame(
                                frame_index,
                                snapshot,
                                target,
                                surface,
                                observation,
                                kind="observation",
                            ),
                        ),
                    )
            except Exception as exc:
                _publish_worker_event(
                    events, observation_events, diagnostics,
                    RawServoEvent(
                        generation,
                        "error",
                        output_dir=None if output_dir is None else str(output_dir),
                        error=str(exc),
                        hard=True,
                    ),
                )
                gate.cancel(generation)
    finally:
        if reference_updater is not None:
            reference_updater.close()
        if camera is not None:
            camera.close()


class RawServoRuntime:
    """Operator gating, watchdog, diagnostics, and direct velocity publication."""

    def __init__(
        self,
        config: Any,
        *,
        publish: Callable[[str], None],
        requests: queue.Queue[int | None] | None = None,
        events: queue.Queue[RawServoEvent] | None = None,
        gate: GenerationGate | None = None,
        stop_event: threading.Event | None = None,
        logger: Callable[[str], None] = print,
        monotonic: Callable[[], float] = time.monotonic,
        diagnostics: AsyncFrameDiagnosticsWriter | None = None,
        orientation_provider: (
            Callable[[float], Mapping[str, Any] | None] | None
        ) = None,
    ):
        self.config = config
        self.publish = publish
        self.requests = requests or queue.Queue(maxsize=1)
        self.events = events or queue.Queue()
        self.observation_events: queue.Queue[RawServoEvent] = queue.Queue(maxsize=1)
        self.gate = gate or GenerationGate()
        self.stop_event = stop_event or threading.Event()
        self.logger = logger
        self.monotonic = monotonic
        self.controller = VisualServoController(
            target_distance_m=config.raw_target_distance_m,
            forward_tolerance_m=config.raw_forward_tolerance_m,
            lateral_tolerance_m=config.raw_lateral_tolerance_m,
            command_ttl_s=config.raw_command_ttl_s,
            max_run_s=config.raw_max_run_s,
            max_lateral_speed_m_s=config.raw_max_lateral_speed_m_s,
            horizontal_guard_fraction=config.raw_horizontal_guard_fraction,
            horizontal_recovery_fraction=config.raw_horizontal_recovery_fraction,
        )
        self.generation = 0
        self.phase = "idle"
        self.output_dir: str | None = None
        self._diagnostics = diagnostics
        self.orientation_provider = orientation_provider
        self.last_observation_at: float | None = None
        self.last_event_produced_at: float | None = None
        self.last_event_received_at: float | None = None
        self.last_applied_frame_index: int | None = None
        self.soft_stale = False
        self.next_publish_at: float | None = None
        self._shutdown = False

    def _zero(self) -> ServoCommand:
        return ServoCommand(0.0, 0.0, 0.0, self.config.raw_command_ttl_s)

    def _publish(self, command: ServoCommand, action: str) -> None:
        self.publish(build_servo_velocity_message(command, action=action))

    def _stop_sequence(self) -> None:
        for _ in range(self.config.final_stop_count):
            self._publish(self._zero(), "stop")

    def _record(self, event: str, **fields: Any) -> None:
        directory = Path(self.output_dir or self.config.output_root).resolve()
        try:
            directory.mkdir(parents=True, exist_ok=True)
            with (directory / "raw_servo_events.jsonl").open("a", encoding="utf-8") as handle:
                handle.write(
                    json.dumps(
                        {
                            "timestamp_unix_s": time.time(),
                            "event": event,
                            "generation": self.generation,
                            **fields,
                        },
                        ensure_ascii=False,
                    )
                    + "\n"
                )
        except OSError as exc:
            self.logger(f"[RawServo] diagnostic write failed: {exc}")

    @property
    def diagnostics(self) -> AsyncFrameDiagnosticsWriter:
        if self._diagnostics is None:
            self._diagnostics = AsyncFrameDiagnosticsWriter(logger=self.logger)
        return self._diagnostics

    def _controller_diagnostics(self) -> dict[str, Any]:
        return {
            "phase": self.controller.phase,
            "resume_phase": self.controller.resume_phase,
            "vertical_resume_phase": self.controller.vertical_resume_phase,
            "transition_reason": self.controller.last_transition_reason,
            "filtered_errors": list(self.controller.last_errors),
            "invalid_frames": self.controller.invalid_frames,
            "stable_frames": self.controller.stable_frames,
            "yaw_stable_frames": self.controller.yaw_stable_frames,
            "recenter_stable_frames": self.controller.recenter_stable_frames,
            "vertical_recenter_stable_frames": (
                self.controller.vertical_recenter_stable_frames
            ),
        }

    def _orientation_diagnostics(
        self, now: float
    ) -> Mapping[str, Any] | None:
        if self.orientation_provider is None:
            return None
        try:
            value = self.orientation_provider(float(now))
            return None if value is None else dict(value)
        except Exception as exc:
            self.logger(
                "[RawServo] WARNING orientation telemetry unavailable: "
                f"{exc}"
            )
            return None

    @staticmethod
    def _command_diagnostics(command: ServoCommand) -> dict[str, float]:
        return {
            "vx": command.vx,
            "vy": command.vy,
            "wz": command.wz,
            "duration_s": command.duration,
        }

    def _discard_event_diagnostic(self, event: RawServoEvent) -> None:
        _submit_diagnostic_decision(
            self._diagnostics,
            event,
            control_applied=False,
        )

    def _drain_waiting_observations(self) -> None:
        while True:
            try:
                event = self.observation_events.get_nowait()
            except queue.Empty:
                return
            self._discard_event_diagnostic(event)

    def _finish(self, reason: str, now: float) -> None:
        if self.phase == "idle":
            return
        self._record(
            "finished",
            reason=reason,
            errors=self.controller.last_errors,
            cumulative_translation_m=self.controller.cumulative_translation_m,
            cumulative_yaw_rad=self.controller.cumulative_yaw_rad,
        )
        self.gate.cancel(self.generation)
        self.phase = "idle"
        self.last_observation_at = None
        self.soft_stale = False
        self.last_applied_frame_index = None
        self._stop_sequence()
        self.next_publish_at = float(now) + 1.0 / self.config.planner_hz
        self.logger(f"[RawServo] STOP {reason}; press N for a new target")

    def handle_key(self, key: str, *, now: float) -> str:
        normalized = str(key).lower()
        if normalized == "x":
            self.cancel("exit", now)
            return "exit"
        if key == " ":
            self.cancel("operator_space", now)
            return "cancelled"
        if normalized != "n":
            return "ignored"
        if self.phase != "idle" or self.stop_event.is_set():
            self.logger("[RawServo] BUSY request rejected")
            return "busy"
        candidate = self.generation + 1
        try:
            self.requests.put_nowait(candidate)
        except queue.Full:
            self.logger("[RawServo] BUSY worker request queue")
            return "busy"
        self.generation = candidate
        self.phase = "inference"
        self.output_dir = None
        self.soft_stale = False
        self.last_applied_frame_index = None
        self.gate.activate(candidate)
        self._publish(self._zero(), "hold")
        self.next_publish_at = float(now) + 1.0 / self.config.planner_hz
        self.logger(f"[RawServo] TARGET INIT generation={candidate}")
        return "started"

    def cancel(self, reason: str, now: float) -> None:
        self.gate.cancel()
        self._drain_waiting_observations()
        self.generation += 1
        self.phase = "idle"
        self.last_observation_at = None
        self.soft_stale = False
        self.last_applied_frame_index = None
        while True:
            try:
                self.requests.get_nowait()
            except queue.Empty:
                break
        self._stop_sequence()
        self.next_publish_at = float(now) + 1.0 / self.config.planner_hz
        self.logger(f"[RawServo] STOP {reason}")

    def accept_event(self, event: RawServoEvent, *, now: float) -> bool:
        if event.generation != self.generation or self.phase == "idle":
            self._discard_event_diagnostic(event)
            return False
        frame_index = None if event.frame is None else int(event.frame.frame_index)
        if (
            frame_index is not None
            and self.last_applied_frame_index is not None
            and frame_index <= self.last_applied_frame_index
        ):
            self._record(
                "out_of_order_frame_discarded",
                frame_index=frame_index,
                last_applied_frame_index=self.last_applied_frame_index,
            )
            self._discard_event_diagnostic(event)
            return False
        received_at = float(now)
        produced_at = (
            received_at
            if event.produced_at_monotonic is None
            else float(event.produced_at_monotonic)
        )
        self.last_event_produced_at = produced_at
        self.last_event_received_at = received_at
        if (
            event.kind == "observation"
            and received_at - produced_at > self.config.raw_camera_stale_s
        ):
            self._record(
                "stale_observation_discarded",
                produced_at_monotonic=produced_at,
                received_at_monotonic=received_at,
            )
            self._discard_event_diagnostic(event)
            return False
        if event.output_dir is not None and event.output_dir != self.output_dir:
            self.output_dir = event.output_dir
        if event.kind == "error":
            self._discard_event_diagnostic(event)
            self.logger(f"[RawServo] FAILURE {event.error}")
            self.controller.reset(now)
            self.controller.note_invalid(event.error or "worker error", hard=True, now=now)
            self._finish(self.controller.terminal_reason or "worker error", now)
            return True
        previous_command = self.controller.current
        recovered_from_soft_stale = False
        if event.kind == "initialized":
            if self.phase != "inference" or event.observation is None:
                self._discard_event_diagnostic(event)
                return False
            self.phase = "aligning"
            self.controller.reset(now)
            self.last_observation_at = float(now)
            command = self.controller.update(event.observation, now=now)
            self._record("initialized", details=dict(event.details or {}))
            self.logger(f"[RawServo] ALIGNING output={self.output_dir}")
        elif event.kind == "observation":
            if self.phase != "aligning" or event.observation is None:
                self._discard_event_diagnostic(event)
                return False
            self.last_observation_at = produced_at
            if self.soft_stale:
                self.soft_stale = False
                recovered_from_soft_stale = True
                self._record("camera_soft_recovered")
                self.logger("[RawServo] RESUME camera stream recovered")
            command = self.controller.update(event.observation, now=now)
        elif event.kind == "invalid":
            if self.phase != "aligning":
                self._discard_event_diagnostic(event)
                return False
            self.last_observation_at = produced_at
            command = self.controller.note_invalid(
                event.error or "invalid perception", hard=event.hard, now=now
            )
        else:
            self._discard_event_diagnostic(event)
            return False
        _submit_diagnostic_decision(
            self._diagnostics,
            event,
            control_applied=True,
            controller_state=self._controller_diagnostics(),
            command=self._command_diagnostics(command),
            orientation=self._orientation_diagnostics(now),
        )
        self._record(
            "control_update",
            perception_kind=event.kind,
            perception_error=event.error,
            hard=event.hard,
            vx=command.vx,
            vy=command.vy,
            wz=command.wz,
            errors=self.controller.last_errors,
            invalid_frames=self.controller.invalid_frames,
            stable_frames=self.controller.stable_frames,
            controller_phase=self.controller.phase.value,
            resume_phase=(
                None
                if self.controller.resume_phase is None
                else self.controller.resume_phase.value
            ),
            vertical_resume_phase=(
                None
                if self.controller.vertical_resume_phase is None
                else self.controller.vertical_resume_phase.value
            ),
            vertical_recenter_stable_frames=(
                self.controller.vertical_recenter_stable_frames
            ),
            transition_reason=self.controller.last_transition_reason,
            event_details=dict(event.details or {}),
        )
        if (
            not self.controller.terminal
            and (
                recovered_from_soft_stale
                or (
                    command.velocity == (0.0, 0.0, 0.0)
                    and previous_command.velocity != (0.0, 0.0, 0.0)
                )
            )
        ):
            self._publish(command, "visual_servo")
            self.next_publish_at = float(now) + 1.0 / self.config.planner_hz
        if self.controller.terminal:
            self._finish(self.controller.terminal_reason or "terminal", now)
        elif frame_index is not None:
            self.last_applied_frame_index = frame_index
        return True

    def poll_events(self) -> int:
        accepted = 0
        observation_processed = False
        try:
            observation_event = self.observation_events.get_nowait()
        except queue.Empty:
            observation_event = None
        while True:
            try:
                event = self.events.get_nowait()
            except queue.Empty:
                break
            if (
                observation_event is not None
                and observation_event.generation == event.generation
                and observation_event.frame is not None
                and event.frame is not None
                and observation_event.frame.frame_index
                < event.frame.frame_index
            ):
                accepted += int(
                    self.accept_event(
                        observation_event, now=self.monotonic()
                    )
                )
                observation_processed = True
                observation_event = None
            accepted += int(self.accept_event(event, now=self.monotonic()))
        if observation_event is None:
            if observation_processed:
                return accepted
            try:
                observation_event = self.observation_events.get_nowait()
            except queue.Empty:
                return accepted
        return accepted + int(
            self.accept_event(observation_event, now=self.monotonic())
        )

    def publish_due(self, now: float) -> ServoCommand | None:
        timestamp = float(now)
        if self.next_publish_at is None:
            self.next_publish_at = timestamp
        if self.phase == "aligning" and self.controller.stop_if_timed_out(
            now=timestamp
        ):
            self._finish(
                self.controller.terminal_reason or "maximum run time reached", timestamp
            )
            return self._zero()
        if timestamp + 1.0e-12 < self.next_publish_at:
            return None
        if (
            self.phase == "aligning"
            and self.last_observation_at is not None
            and timestamp - self.last_observation_at > self.config.raw_camera_stale_s
        ):
            if not self.soft_stale:
                self.soft_stale = True
                self.controller._integrate(timestamp)
                self.controller.current = self._zero()
                self._record("camera_soft_stale")
                self.logger("[RawServo] HOLD camera stream soft stale")
        command = (
            self.controller.current
            if self.phase == "aligning" and not self.soft_stale
            else self._zero()
        )
        self._publish(command, "visual_servo" if self.phase == "aligning" else "hold")
        self.next_publish_at = timestamp + 1.0 / self.config.planner_hz
        return command

    def shutdown(self) -> None:
        if self._shutdown:
            return
        self._shutdown = True
        self.stop_event.set()
        self.cancel("shutdown", self.monotonic())
        try:
            self.requests.put_nowait(None)
        except queue.Full:
            pass

    def flush_diagnostics(self) -> None:
        self._drain_waiting_observations()
        if self._diagnostics is not None:
            self._diagnostics.close(drain=True)
        self.logger("[RawServo] diagnostics flushed")


def run_raw_servo_loop(
    runtime: RawServoRuntime,
    *,
    read_key: Callable[[], str | None],
    monotonic: Callable[[], float] = time.monotonic,
    sleep: Callable[[float], None] = time.sleep,
    running: Callable[[], bool] = lambda: True,
) -> None:
    try:
        while running():
            now = monotonic()
            key = read_key()
            if key is not None and runtime.handle_key(key, now=now) == "exit":
                break
            runtime.poll_events()
            runtime.publish_due(now)
            sleep(min(0.01, 0.25 / runtime.config.planner_hz))
    except KeyboardInterrupt:
        pass
    finally:
        runtime.shutdown()
