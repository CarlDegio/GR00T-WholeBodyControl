def normalized_bbox_to_pixels(
    bbox: tuple[float, float, float, float], width: int, height: int
) -> tuple[float, float, float, float]:
    return (
        bbox[0] * width / 1000.0,
        bbox[1] * height / 1000.0,
        bbox[2] * width / 1000.0,
        bbox[3] * height / 1000.0,
    )

def pixel_bbox_to_normalized(
    bbox: Sequence[float], width: int, height: int
) -> tuple[float, float, float, float]:
    if width <= 0 or height <= 0:
        raise ValueError("image dimensions must be positive")
    if len(bbox) != 4:
        raise ValueError("pixel bbox must contain four values")
    x1, y1, x2, y2 = (float(item) for item in bbox)
    normalized = (
        max(0.0, min(1000.0, 1000.0 * x1 / width)),
        max(0.0, min(1000.0, 1000.0 * y1 / height)),
        max(0.0, min(1000.0, 1000.0 * x2 / width)),
        max(0.0, min(1000.0, 1000.0 * y2 / height)),
    )
    return _validate_bbox(list(normalized), "pixel_bbox")



def bbox_iou(a: tuple[float, ...], b: tuple[float, ...]) -> float:
    x1, y1 = max(a[0], b[0]), max(a[1], b[1])
    x2, y2 = min(a[2], b[2]), min(a[3], b[3])
    intersection = max(0.0, x2 - x1) * max(0.0, y2 - y1)
    area_a = max(0.0, a[2] - a[0]) * max(0.0, a[3] - a[1])
    area_b = max(0.0, b[2] - b[0]) * max(0.0, b[3] - b[1])
    union = area_a + area_b - intersection
    return intersection / union if union > 0.0 else 0.0


